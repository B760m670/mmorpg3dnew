#!/usr/bin/env python3
"""ИСПЫТАТЕЛЬНЫЙ СТЕНД ВОДЫ: разбор и проверка ДО внедрения в игру.

Что вообще делает воду водой (разбор по AAA-конвейеру и по физике):

1. ОПТИКА — почему вода выглядит водой. Главное здесь, а не волны.
   а) ФРЕНЕЛЬ: доля отражения зависит от угла взгляда. Сверху вниз вода почти
      прозрачна (отражает ~2%), вдоль поверхности — почти зеркало (>50%).
      Именно это, а не «синий цвет», читается глазом как вода.
   б) ПОГЛОЩЕНИЕ (Бугер-Ламберт-Бер): вода поглощает КРАСНЫЙ во много раз
      быстрее синего. Поэтому глубина сама делает воду сине-зелёной — цвет НЕ
      задаётся художником, он следствие толщи. Коэффициенты — измеренные
      (Pope & Fry, 1997).
   в) РАССЕЯНИЕ на взвеси: планктон и муть. Отсюда РАЗНИЦА озера и реки:
      озеро цветёт (зелёная муть), река несёт глину (бурая), родник прозрачен.
   г) ПРЕЛОМЛЕНИЕ (закон Снелла, n=1.333) — дно смещается и «ломается».
   д) КАУСТИКИ — свет, сфокусированный волнами на дне.

2. ПОВЕРХНОСТЬ — волны. Ключ, который обычно врут: высота волны ОГРАНИЧЕНА
   разгоном (fetch) — длиной разбега ветра над водой. На нашем озере 700 м
   физически НЕ МОГУТ быть морские волны. Формула SMB (Свердруп-Мунк).

3. ТЕЧЕНИЕ — скорость реки из уклона и глубины (формула Маннинга, гидравлика).

4. ВЕЩЕСТВО — плотность, вязкость, поверхностное натяжение (реальные,
   зависят от температуры). Отсюда плавучесть (Архимед) и сопротивление.

Проверка: каждое свойство сверяется с известным ответом. Что не сошлось —
в игру не идёт.
"""
import math

G = 9.81

# --- измеренные коэффициенты поглощения чистой воды, 1/м (Pope & Fry 1997) ---
ABSORPTION = {
    "синий 450нм": 0.0145,
    "зелёный 550нм": 0.0638,
    "жёлтый 580нм": 0.0922,
    "красный 650нм": 0.3400,
    "тёмно-красный 700нм": 0.6240,
}

# --- вещество (при 20 °C) ---
RHO_W = 998.2          # плотность, кг/м3
MU_W = 1.002e-3        # динамическая вязкость, Па·с
SIGMA_W = 0.0728       # поверхностное натяжение, Н/м
IOR_W = 1.333          # показатель преломления


def fresnel_schlick(cos_theta, ior=IOR_W):
    r0 = ((ior - 1.0) / (ior + 1.0)) ** 2
    return r0 + (1.0 - r0) * (1.0 - cos_theta) ** 5


def fresnel_exact(cos_i, ior=IOR_W):
    """Точные формулы Френеля (неполяризованный свет) — эталон для проверки."""
    sin_t = (1.0 / ior) * math.sqrt(max(0.0, 1.0 - cos_i * cos_i))
    if sin_t >= 1.0:
        return 1.0
    cos_t = math.sqrt(max(0.0, 1.0 - sin_t * sin_t))
    rs = ((ior * cos_i - cos_t) / (ior * cos_i + cos_t)) ** 2
    rp = ((cos_i - ior * cos_t) / (cos_i + ior * cos_t)) ** 2
    return 0.5 * (rs + rp)


def transmit(depth_m, a):
    """Пропускание через слой воды (Бугер-Ламберт-Бер)."""
    return math.exp(-a * depth_m)


def wave_height_smb(wind_ms, fetch_m):
    """Высота волны, ОГРАНИЧЕННАЯ РАЗГОНОМ (Sverdrup-Munk-Bretschneider).
    Волна не может вырасти больше, чем позволяет длина разбега ветра."""
    if wind_ms <= 0 or fetch_m <= 0:
        return 0.0, 0.0
    u2 = wind_ms * wind_ms
    x = G * fetch_m / u2
    hs = 0.283 * (u2 / G) * math.tanh(0.0125 * x ** 0.42)
    ts = 7.54 * (wind_ms / G) * math.tanh(0.077 * x ** 0.25)
    return hs, ts


def manning_velocity(depth_m, slope, n=0.035):
    """Скорость потока (Маннинг): широкое русло, R ≈ глубина.
    n=0.035 — естественный извилистый ручей/река с растительностью."""
    return (1.0 / n) * depth_m ** (2.0 / 3.0) * math.sqrt(max(slope, 1e-9))


def main():
    ok = True
    print("=" * 72)
    print("ИСПЫТАНИЕ 1: ФРЕНЕЛЬ — почему вода то зеркало, то стекло")
    print("=" * 72)
    print("  %-22s %10s %10s %8s" % ("угол взгляда", "точно", "Шлик", "ошибка"))
    worst = 0.0
    for ang in (0, 30, 45, 60, 75, 85, 89):
        c = math.cos(math.radians(ang))
        ex = fresnel_exact(c)
        sc = fresnel_schlick(c)
        err = abs(ex - sc)
        worst = max(worst, err)
        print("  %3d° от вертикали      %9.1f%% %9.1f%% %7.3f" % (ang, ex * 100, sc * 100, err))
    print("\n  сверху (0°): %.1f%% — вода ПРОЗРАЧНА, видно дно" % (fresnel_exact(1.0) * 100))
    print("  вдоль (85°): %.1f%% — вода ЗЕРКАЛО, отражает небо" % (
        fresnel_exact(math.cos(math.radians(85))) * 100))
    if not (0.015 < fresnel_exact(1.0) < 0.025):
        print("  ! отражение сверху обязано быть ~2% (n=1.333)")
        ok = False
    else:
        print("  OK: 2%% сверху — совпадает с физикой (n=%.3f)" % IOR_W)
    print("  приближение Шлика годится (макс. ошибка %.3f)" % worst)

    print("\n" + "=" * 72)
    print("ИСПЫТАНИЕ 2: ПОГЛОЩЕНИЕ — глубина САМА красит воду")
    print("=" * 72)
    print("  %-22s %8s %8s %8s %8s" % ("длина волны", "0.5 м", "2 м", "5 м", "20 м"))
    for name, a in ABSORPTION.items():
        print("  %-22s %7.0f%% %7.0f%% %7.0f%% %7.0f%%" % (
            name, transmit(0.5, a) * 100, transmit(2, a) * 100,
            transmit(5, a) * 100, transmit(20, a) * 100))
    red_5 = transmit(5, ABSORPTION["красный 650нм"])
    blue_5 = transmit(5, ABSORPTION["синий 450нм"])
    print("\n  на 5 м: красного осталось %.0f%%, синего %.0f%% -> вода СИНЕ-ЗЕЛЁНАЯ"
          % (red_5 * 100, blue_5 * 100))
    if blue_5 / red_5 < 3.0:
        print("  ! синий обязан проходить в разы дальше красного")
        ok = False
    else:
        print("  OK: синий проходит в %.0f раз дальше красного — цвет НЕ рисуется,"
              % (blue_5 / red_5))
        print("      он СЛЕДСТВИЕ толщи (как в жизни)")

    print("\n" + "=" * 72)
    print("ИСПЫТАНИЕ 3: ВОЛНЫ — разгон (fetch) ограничивает высоту")
    print("=" * 72)
    print("  %-26s %8s %9s %8s" % ("водоём (разгон)", "ветер", "высота", "период"))
    cases = [
        ("пруд Гатчины (150 м)", 150, 5.0),
        ("Белое озеро (700 м)", 700, 5.0),
        ("Белое озеро, шторм", 700, 15.0),
        ("Ладога (100 км)", 100000, 15.0),
        ("открытое море (500 км)", 500000, 20.0),
    ]
    for name, fetch, wind in cases:
        h, t = wave_height_smb(wind, fetch)
        print("  %-26s %6.0f м/с %7.2f м %6.1f с" % (name, wind, h, t))
    h_lake, _ = wave_height_smb(5.0, 700)
    h_sea, _ = wave_height_smb(20.0, 500000)
    print("\n  волна на нашем озере: %.2f м (рябь!), в море: %.1f м" % (h_lake, h_sea))
    if h_lake > 0.15:
        print("  ! на озере 700 м не может быть таких волн")
        ok = False
    else:
        print("  OK: на озере физически возможна только РЯБЬ %.0f см — морские волны" % (
            h_lake * 100))
        print("      на пруду были бы ложью (частая ошибка в играх)")

    print("\n" + "=" * 72)
    print("ИСПЫТАНИЕ 4: ТЕЧЕНИЕ — скорость реки из уклона (Маннинг)")
    print("=" * 72)
    print("  %-30s %9s %10s" % ("река", "глубина", "скорость"))
    # уклон рек Гатчины: перепад мал (равнина) — порядка 0.5-1 м на км
    for name, d, s in [("Парица (равнинная, 0.7 м/км)", 0.8, 0.0007),
                       ("Колпанка (0.5 м/км)", 0.6, 0.0005),
                       ("ручей на склоне (10 м/км)", 0.3, 0.010),
                       ("горная река (50 м/км)", 1.0, 0.050)]:
        v = manning_velocity(d, s)
        print("  %-30s %7.1f м %8.2f м/с" % (name, d, v))
    v_plain = manning_velocity(0.8, 0.0007)
    print("\n  наши равнинные реки: %.2f м/с (%.1f км/ч) — медленное течение" % (
        v_plain, v_plain * 3.6))
    if not (0.1 < v_plain < 1.0):
        print("  ! скорость равнинной реки вне разумного (0.1-1 м/с)")
        ok = False
    else:
        print("  OK: совпадает с наблюдаемым для равнинных рек (0.2-0.6 м/с)")

    print("\n" + "=" * 72)
    print("ИСПЫТАНИЕ 5: ВЕЩЕСТВО — плотность, вязкость, натяжение")
    print("=" * 72)
    print("  плотность        %.1f кг/м3" % RHO_W)
    print("  вязкость         %.4f Па·с (в 55 раз гуще воздуха)" % MU_W)
    print("  натяжение        %.4f Н/м (держит насекомых, скругляет капли)" % SIGMA_W)
    print("  преломление      %.3f" % IOR_W)
    # проверка плавучести: что плавает, что тонет
    print("\n  ПЛАВУЧЕСТЬ (Архимед) — доля тела под водой:")
    for name, rho in [("сосна (сухая)", 500), ("дуб", 750), ("человек", 985),
                      ("лёд", 917), ("гранит", 2700)]:
        if rho < RHO_W:
            print("    %-16s %.0f кг/м3 -> плавает, погружён на %.0f%%" % (
                name, rho, rho / RHO_W * 100))
        else:
            print("    %-16s %.0f кг/м3 -> ТОНЕТ" % (name, rho))
    if abs(917 / RHO_W - 0.919) > 0.01:
        ok = False
    else:
        print("  OK: лёд погружён на 92%% — совпадает с известным (айсберг «на 1/10 сверху»)")

    print("\n" + "=" * 72)
    print("ИТОГ СТЕНДА: %s" % (
        "ФИЗИКА ВОДЫ ВЕРНА — можно строить" if ok else "ЕСТЬ ПРОВАЛЫ — в игру не нести"))
    print("=" * 72)
    print("""
ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ НАШЕЙ ВОДЫ (выводы стенда):
  1. Цвет воды НЕ задаём краской — он выходит сам из глубины и мутности.
     Значит шейдеру нужна ГЛУБИНА под пикселем, а не «синий цвет».
  2. Главный признак воды — Френель, а не цвет. Вдоль поверхности зеркало,
     сверху прозрачно. Без этого вода выглядит крашеным стеклом.
  3. Наши водоёмы малы -> волны только РЯБЬ (см. испытание 3). Морские волны
     на пруду были бы враньём.
  4. Озеро и река отличаются НЕ картинкой, а веществом: озеро мутное от
     планктона и почти стоячее, река прозрачнее, но течёт 0.2-0.6 м/с и несёт
     муть от берегов.
  5. Течение берём из настоящей гидрологии (build_hydrology.py), а не рисуем.
""")


if __name__ == "__main__":
    main()
