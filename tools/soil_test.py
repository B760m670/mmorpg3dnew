#!/usr/bin/env python3
"""ИСПЫТАНИЯ ПОЧВЫ — проверяем, ведёт ли себя наша почва как НАСТОЯЩАЯ.

Не «похоже на глаз», а инженерные опыты с известным ответом из грунтоведения.
Если тест не сходится со справочником — почва ненастоящая, внедрять нельзя.

Опыты:
 1. НЕСУЩАЯ СПОСОБНОСТЬ (Терцаги): выдержит ли почва человека/лошадь/пушку.
 2. ОТКОС ЯМЫ: под каким углом осыпаются стенки; глубина устойчивой стенки.
 3. ВПИТЫВАНИЕ ДОЖДЯ: за сколько промокает верх, когда лужи (k_sat vs дождь).
 4. ПРЕВРАЩЕНИЕ В ГРЯЗЬ: сколько дождя нужно, чтобы верх поплыл.
 5. СЖАТИЕ (след): глубина колеи/следа от давления.
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROF = os.path.join(ROOT, "game2/data/real/soil_profile.json")
G = 9.81


def bearing_capacity_kpa(h, width_m=0.1, depth_m=0.0):
    """Терцаги (полосовой штамп): qu = c·Nc + q·Nq + 0.5·γ·B·Nγ"""
    phi = math.radians(h["phi_deg"])
    c = h["cohesion_kpa"]
    gamma = h["rho_d"] * G / 1000.0          # кН/м3
    if phi > 1e-6:
        nq = math.exp(math.pi * math.tan(phi)) * math.tan(math.radians(45) + phi / 2) ** 2
        nc = (nq - 1) / math.tan(phi)
        ng = 2 * (nq + 1) * math.tan(phi)
    else:
        nq, nc, ng = 1.0, 5.14, 0.0
    return c * nc + gamma * depth_m * nq + 0.5 * gamma * width_m * ng


def stable_wall_m(h):
    """Реальная высота вертикальной стенки ямы до обвала.

    Теоретический предел Rankine Hc = 4c/γ·tan(45+φ/2) — для ИДЕАЛЬНОГО грунта
    без трещин, разгрузки и воды. На практике стенка обваливается ЗНАЧИТЕЛЬНО
    раньше: в грунте есть трещины отрыва, влага снижает c', край нагружен.
    Инженерная практика (и нормы по креплению траншей): запас ~2, а сцепление
    в поле падает примерно вдвое от лабораторного. Итого ~Hc/4.
    Сверка: суглинок (A) -> ~1.5-1.8 м — ровно та глубина, с которой траншеи
    обязаны крепить. Песок/подзол -> сыпется почти сразу."""
    gamma = h["rho_d"] * G / 1000.0
    hc = 4.0 * h["cohesion_kpa"] / gamma * math.tan(math.radians(45) + math.radians(h["phi_deg"]) / 2)
    return hc / 4.0


def infiltration_mm_h(h):
    """Скорость впитывания = k_sat (м/с) -> мм/ч."""
    return h["k_sat"] * 3600.0 * 1000.0


def main():
    prof = json.load(open(PROF))
    H = prof["horizons"]
    ok = True

    print("=== ОПЫТ 1: НЕСУЩАЯ СПОСОБНОСТЬ (выдержит ли вес) ===")
    # реальные давления: человек ~50 кПа (ботинок), лошадь ~200 кПа (копыто),
    # полевая пушка на колесе ~300 кПа
    loads = [("человек (ботинок)", 50), ("лошадь (копыто)", 200), ("пушка (колесо)", 300)]
    for h in H[:5]:
        qu = bearing_capacity_kpa(h, width_m=0.12, depth_m=0.0)
        verdicts = []
        for name, p in loads:
            verdicts.append("%s:%s" % (name.split()[0], "держит" if qu > p else "ПРОВАЛ"))
        print("  %-3s qu=%7.0f кПа  %s" % (h["code"], qu, "  ".join(verdicts)))
    # физичность: подстилка должна проваливаться под пушкой, морена — держать
    qu_litter = bearing_capacity_kpa(H[0], 0.12)
    qu_moraine = bearing_capacity_kpa(H[4], 0.12)
    if not (qu_litter < 300 < qu_moraine):
        print("  ! нефизично: подстилка обязана проседать, морена — держать")
        ok = False
    else:
        print("  OK: рыхлая подстилка проседает под пушкой, морена держит")

    print("\n=== ОПЫТ 2: ОТКОС И СТЕНКА ЯМЫ (обвал) ===")
    for h in H[:6]:
        print("  %-3s откос %2.0f°, вертикальная стенка держится до %.2f м" % (
            h["code"], h["repose_deg"], stable_wall_m(h)))
    # песчаная подстилка/подзол не должны держать высокую стенку, глина — должна
    if stable_wall_m(H[2]) >= stable_wall_m(H[5]):
        print("  ! нефизично: глина обязана держать стенку лучше подзола")
        ok = False
    else:
        print("  OK: глина держит стенку, подзол осыпается (яма в песке оплывает)")
    # СВЕРКА С ПРАКТИКОЙ: траншею в суглинке (A) крепят с ~1.5 м — наша стенка
    # обязана попасть в этот порядок, иначе яма будет «резиновой»
    wa = stable_wall_m(H[1])
    if not (0.8 <= wa <= 2.5):
        print("  ! стенка в суглинке %.2f м — вне практики (крепят с ~1.5 м)" % wa)
        ok = False
    else:
        print("  OK: стенка в суглинке %.2f м — совпадает с практикой крепления траншей" % wa)

    print("\n=== ОПЫТ 3: ВПИТЫВАНИЕ ДОЖДЯ (когда лужи) ===")
    rains = [("морось", 2.0), ("дождь", 10.0), ("ливень", 50.0)]
    for h in H[:4]:
        inf = infiltration_mm_h(h)
        pud = [r[0] for r in rains if r[1] > inf]
        print("  %-3s впитывает %8.1f мм/ч -> лужи при: %s" % (
            h["code"], inf, ", ".join(pud) if pud else "нет (всё впитывает)"))
    # глина обязана давать лужи даже от мороси, подстилка — впитывать ливень
    if not (infiltration_mm_h(H[5]) < 2.0 < infiltration_mm_h(H[0])):
        print("  ! нефизично: глина=водоупор, подстилка=губка")
        ok = False
    else:
        print("  OK: глина — водоупор (лужи), подстилка — губка (впитывает ливень)")

    print("\n=== ОПЫТ 4: ПРЕВРАЩЕНИЕ В ГРЯЗЬ ===")
    for h in H[:5]:
        # сколько мм дождя, чтобы верхние 10 см дошли от завядания до порога грязи
        need = (h["mud_threshold"] - h["wilt"]) * 0.10 * 1000.0
        print("  %-3s грязь при влажности > %.2f  (нужно ~%.0f мм дождя в верх 10 см)" % (
            h["code"], h["mud_threshold"], need))

    print("\n=== ОПЫТ 5: СЛЕД/КОЛЕЯ (сжатие под нагрузкой) ===")
    for h in H[:4]:
        qu = bearing_capacity_kpa(h, 0.12)
        for name, p in [("человек", 50), ("телега", 250)]:
            # осадка ~ доля от превышения нагрузки над прочностью, ограничена пористостью
            if p < qu:
                s = 0.10 * (p / qu) ** 2 * h["poros"]
            else:
                s = 0.10 * h["poros"] + 0.05 * (p / qu - 1.0)
            print("  %-3s %-8s давление %3d кПа -> след %.1f см" % (h["code"], name, p, s * 100))

    print("\n  ИТОГ ИСПЫТАНИЙ: %s" % (
        "ПОЧВА ВЕДЁТ СЕБЯ КАК НАСТОЯЩАЯ" if ok else "ЕСТЬ НЕФИЗИЧНОСТЬ — НЕ ВНЕДРЯТЬ"))


if __name__ == "__main__":
    main()
