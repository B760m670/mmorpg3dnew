# границы правдоподобия для самопроверки [Ч]
LIMITS = dict(shoots_m2=(300, 25000), cover=(0.30, 1.00), h_cm=(5, 230))


def check():
    """Самопроверка ДО того, как из этих чисел вырастет геометрия."""
    bad = []
    print("== ПРОВЕРКА ТРАВОСТОЯ ==")
    for name, c in COMMUNITIES.items():
        s = sum(c["mix"].values())
        if abs(s - 1.0) > 1e-6:
            bad.append("%s: доли видов дают %.3f вместо 1.000" % (name, s))
        for sp in c["mix"]:
            if sp not in SPECIES:
                bad.append("%s: неизвестный вид «%s»" % (name, sp))
        lo, hi = LIMITS["shoots_m2"]
        if not lo <= c["shoots_m2"] <= hi:
            bad.append("%s: %d побегов/м² вне %d..%d" % (name, c["shoots_m2"], lo, hi))
        lo, hi = LIMITS["cover"]
        if not lo <= c["cover"] <= hi:
            bad.append("%s: покрытие %.2f вне %.2f..%.2f" % (name, c["cover"], lo, hi))
        if abs(c["cover"] + c["litter"] - 1.0) > 1e-6:
            bad.append("%s: покрытие+подстилка = %.2f, должно 1.00"
                       % (name, c["cover"] + c["litter"]))
        # высота травостоя обязана лежать внутри высот его же видов —
        # КРОМЕ скошенных: газон и есть те же травы, срезанные ниже природной
        sp_lo = min(SPECIES[s]["h_cm"][0] for s in c["mix"])
        sp_hi = max(SPECIES[s]["h_cm"][1] for s in c["mix"])
        if c.get("mown"):
            if c["h_cm"][1] >= sp_lo:
                bad.append("%s: помечен скошенным, но травостой %d см не ниже "
                           "природных %d см — тогда он не скошен"
                           % (name, c["h_cm"][1], sp_lo))
        elif not (sp_lo <= c["h_cm"][0] and c["h_cm"][1] <= sp_hi):
            bad.append("%s: травостой %d-%d см не помещается в виды %d-%d см"
                       % (name, c["h_cm"][0], c["h_cm"][1], sp_lo, sp_hi))
        # сколько дернин на м²: побеги / побегов с дернины (взвешенно)
        per = sum(f * SPECIES[s]["shoots"] for s, f in c["mix"].items())
        tufts = c["shoots_m2"] / per
        print("  %-6s зона %d: %6d побег/м² · дернин %5.0f/м² · покрытие %3.0f%% · "
              "травостой %3d-%3d см · видов %d"
              % (name, c["zone"], c["shoots_m2"], tufts, c["cover"] * 100,
                 c["h_cm"][0], c["h_cm"][1], len(c["mix"])))

    for name, s in SPECIES.items():
        lo, hi = s["h_cm"]
        if lo >= hi:
            bad.append("%s: высота %d-%d см задом наперёд" % (name, lo, hi))
        gl, gh = LIMITS["h_cm"]
        if not (gl <= lo and hi <= gh):
            bad.append("%s: высота %d-%d см вне %d..%d" % (name, lo, hi, gl, gh))

    used = set()
    for c in COMMUNITIES.values():
        used |= set(c["mix"])
    unused = set(SPECIES) - used
    if unused:
        bad.append("виды описаны, но нигде не сеются: %s" % ", ".join(sorted(unused)))

    print("  видов всего %d, сообществ %d" % (len(SPECIES), len(COMMUNITIES)))
    if bad:
        print("ОШИБКИ:")
        for b in bad:
            print("   -", b)
        return False
    print("  все проверки пройдены")
    return True


