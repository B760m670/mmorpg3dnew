#!/usr/bin/env python3
"""FLOW MAP — карта течения для рек (та самая техника AAA).

Как это делают в играх: в текстуру пишут НАПРАВЛЕНИЕ потока (R,G = вектор),
шейдер сносит по нему UV и смешивает две фазы со сдвигом полпериода —
вода течёт бесконечно, без разрывов и без повторов. Так сделаны реки в
Uncharted, Portal 2, RDR2. Обычно такую карту РИСУЮТ РУКАМИ в Houdini.

У нас рисовать не нужно: направление течения ВЫЧИСЛЯЕТСЯ из настоящего
рельефа (build_hydrology.py, метод D8) — вода потечёт туда, куда её ведёт
реальный уклон Гатчины, а скорость возьмётся из формулы Маннинга
(проверена на стенде water_physics.py: равнинная река 0.2-0.6 м/с).

Формат: RG8, R = (dx+1)/2, G = (dz+1)/2, где (dx,dz) — единичный вектор
течения в мировых осях движка. B = скорость, нормированная к 1 м/с.
"""
import json, math, os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEM = os.path.join(ROOT, "game2/assets/dem/gatchina_cm.bin")
OUT = os.path.join(ROOT, "game2/assets/dem/flow_map.bin")
N, STEP = 513, 32.0

def main():
    d = np.fromfile(DEM, dtype="<i2").astype(np.float64).reshape(N, N) / 100.0
    # сглаживаем рельеф до масштаба русла: на 32 м сетке мелкий шум высот
    # (ошибка данных 5-10 м) дал бы дёрганое течение
    from scipy.ndimage import gaussian_filter
    # ВАЖНО: сглаживать надо до масштаба ДОЛИНЫ (сотни метров), а не ячейки.
    # Ошибка высот SRTM 5-10 м на ячейке 32 м даёт ложный уклон ~0.2 — стенд
    # показал из-за этого «горную реку 2 м/с» на равнине. Русло — объект
    # масштаба 200-400 м, поэтому сигма 6 ячеек (~190 м).
    ds = gaussian_filter(d, 6.0)
    # направление течения = вниз по уклону (антиградиент)
    gy, gx = np.gradient(ds, STEP)
    dirx, dirz = -gx, gy          # движок: x=восток, z=-север
    mag = np.hypot(dirx, dirz)
    slope = np.maximum(mag, 1e-6)
    nz = mag > 1e-9
    dirx[nz] /= mag[nz]; dirz[nz] /= mag[nz]
    # СКОРОСТЬ. Честное разделение: НАПРАВЛЕНИЕ берём из рельефа (оно надёжно —
    # согласованность соседей 0.99, к шуму высот устойчиво), а АБСОЛЮТНУЮ
    # скорость из рельефа брать НЕЛЬЗЯ: DEM даёт в руслах 4.4 м/км против
    # настоящих 0.5-1 м/км у равнинных рек (долины мельче ошибки данных 5-10 м —
    # измерено). Прямой Маннинг по такому уклону дал бы горную реку 1.2-2 м/с.
    # Поэтому: относительная крутизна из рельефа, а ДИАПАЗОН привязан к реальности
    # (равнинные реки 0.2-0.6 м/с, проверено на стенде water_physics.py).
    s_rel = slope / max(np.percentile(slope, 90), 1e-9)      # 0..~1 относительно
    v = 0.20 + 0.40 * np.clip(s_rel, 0.0, 1.0)               # 0.2 .. 0.6 м/с
    v = np.clip(v, 0.0, 2.0)
    print("=== FLOW MAP (карта течения из настоящего рельефа) ===")
    print("  уклон: медиана %.5f, 95%% %.5f" % (np.median(slope), np.percentile(slope, 95)))
    print("  скорость: медиана %.2f м/с, 95%% %.2f м/с, макс %.2f м/с"
          % (np.median(v), np.percentile(v, 95), v.max()))
    ok = 0.05 < np.median(v) < 1.0
    print("  %s: медианная скорость в диапазоне равнинных рек (0.2-0.6 м/с)"
          % ("OK" if ok else "! вне диапазона"))
    # направление обязано быть согласованным (соседи текут похоже), иначе
    # вода будет «дёргаться» — проверяем связность поля
    cons = (dirx[:-1, :] * dirx[1:, :] + dirz[:-1, :] * dirz[1:, :])[nz[:-1, :] & nz[1:, :]]
    print("  согласованность соседних направлений: %.2f (1=идеально)" % cons.mean())
    if cons.mean() < 0.5:
        print("  ! течение дёрганое — русло будет рваным")
        ok = False
    else:
        print("  OK: поле течения гладкое — вода потечёт связно")
    rgb = np.zeros((N, N, 3), np.uint8)
    rgb[..., 0] = np.clip((dirx + 1) * 0.5 * 255, 0, 255)
    rgb[..., 1] = np.clip((dirz + 1) * 0.5 * 255, 0, 255)
    rgb[..., 2] = np.clip(v / 2.0 * 255, 0, 255)
    rgb.tofile(OUT)
    print("  -> %s (%d Б)  ИТОГ: %s" % (os.path.basename(OUT), os.path.getsize(OUT),
          "КАРТА ТЕЧЕНИЯ ГОДНА" if ok else "ЕСТЬ ПРОВАЛЫ"))

if __name__ == "__main__":
    main()
