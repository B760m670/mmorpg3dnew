def moon_full(jd):
    T = (jd - 2451545.0) / 36525.0
    Lp = 218.3164477 + 481267.88123421 * T - 0.0015786 * T**2 + T**3 / 538841 - T**4 / 65194000
    D = 297.8501921 + 445267.1114034 * T - 0.0018819 * T**2 + T**3 / 545868 - T**4 / 113065000
    M = 357.5291092 + 35999.0502909 * T - 0.0001536 * T**2 + T**3 / 24490000
    Mp = 134.9633964 + 477198.8675055 * T + 0.0087414 * T**2 + T**3 / 69699 - T**4 / 14712000
    F = 93.2720950 + 483202.0175233 * T - 0.0036539 * T**2 - T**3 / 3526000 + T**4 / 863310000
    A1 = 119.75 + 131.849 * T
    A2 = 53.09 + 479264.290 * T
    A3 = 313.45 + 481266.484 * T
    E = 1 - 0.002516 * T - 0.0000074 * T**2
    Dr, Mr, Mpr, Fr = D * RAD, M * RAD, Mp * RAD, F * RAD

    sl = sr = sb = 0.0
    for d, m, mp, f, cl, cr in TL:
        arg = d * Dr + m * Mr + mp * Mpr + f * Fr
        e = E**abs(m)
        sl += cl * e * math.sin(arg)
        sr += cr * e * math.cos(arg)
    for d, m, mp, f, cb in TB:
        arg = d * Dr + m * Mr + mp * Mpr + f * Fr
        sb += cb * (E**abs(m)) * math.sin(arg)
    sl += 3958 * math.sin(A1 * RAD) + 1962 * math.sin((Lp - F) * RAD) + 318 * math.sin(A2 * RAD)
    sb += (-2235 * math.sin(Lp * RAD) + 382 * math.sin(A3 * RAD)
           + 175 * math.sin((A1 - F) * RAD) + 175 * math.sin((A1 + F) * RAD)
           + 127 * math.sin((Lp - Mp) * RAD) - 115 * math.sin((Lp + Mp) * RAD))

    lam = Lp + sl / 1e6
    bet = sb / 1e6
    dist = 385000.56 + sr / 1000.0
    return lam % 360.0, bet, dist, (Lp % 360.0, F % 360.0, Mp % 360.0, D % 360.0, M % 360.0)


def eq_of(lam, bet, eps=23.439291):
    ll, bb, e = lam * RAD, bet * RAD, eps * RAD
    ra = math.atan2(math.sin(ll) * math.cos(e) - math.tan(bb) * math.sin(e), math.cos(ll))
    dec = math.asin(math.sin(bb) * math.cos(e) + math.cos(bb) * math.sin(e) * math.sin(ll))
    return ra * DEG % 360.0, dec * DEG


def libration(jd):
    lam, bet, dist, (Lp, F, Mp, Dm, M) = moon_full(jd)
    T = (jd - 2451545.0) / 36525.0
    I = 1.54242 * RAD
    Om = (125.0445479 - 1934.1362891 * T + 0.0020754 * T**2 + T**3 / 467441 - T**4 / 60616000) % 360.0
    W = (lam - Om) * RAD                          # Δψ (нутация) опущена (~arcsec)
    bb = bet * RAD
    A = math.atan2(math.sin(W) * math.cos(bb) * math.cos(I) - math.sin(bb) * math.sin(I),
                   math.cos(W) * math.cos(bb))
    l_opt = (A * DEG - F) % 360.0
    if l_opt > 180: l_opt -= 360
    b_opt = math.asin(-math.sin(W) * math.cos(bb) * math.sin(I) - math.sin(bb) * math.cos(I)) * DEG
    # позиционный угол оси P (оптический, физ. либрация опущена)
    eps = 23.439291 * RAD
    ra, dec = eq_of(lam, bet)
    V = Om * RAD
    X = math.sin(I) * math.sin(V)
    Y = math.sin(I) * math.cos(V) * math.cos(eps) - math.cos(I) * math.sin(eps)
    om = math.atan2(X, Y)
    P = math.asin(math.sqrt(X * X + Y * Y) * math.cos(ra * RAD - om) / math.cos(b_opt * RAD)) * DEG
    return l_opt, b_opt, P, dist, ra, dec


