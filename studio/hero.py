def landmarks(me):
    """Измерить тело: где у НЕГО лодыжка, колено, пах, плечи, подбородок.

    ПЕРВЫЙ ЗАМЕР СОВРАЛ, И ВРАНЬЁ БЫЛО ВИДНО ПО ЧИСЛАМ: колено 0.499 при
    пахе 0.543. Так не бывает. Причина — Т-ПОЗА: руки раскинуты в стороны, и
    «самая широкая точка среза» на любой высоте выше пояса показывает руки, а
    не корпус. Поэтому корпус меряется в узкой полосе у оси, а руки в замер не
    попадают вовсе.

    ПАХ ищется не по ширине, а по РАЗРЫВУ: ниже паха срез распадается на две
    ноги, и между ними в сечении зияет дыра. Самая нижняя высота, где дыры уже
    нет, и есть пах. Ширина этого не различает — две ноги врозь и один таз
    могут давать одинаковый габарит.
    """
    zs = [v.co.z for v in me.vertices]
    lo, hi = min(zs), max(zs)
    H = hi - lo
    N = 260
    sl = {}
    for v in me.vertices:
        i = min(N - 1, int((v.co.z - lo) / H * N))
        sl.setdefault(i, []).append(v.co.x)

    def z_of(i):
        return lo + (i + 0.5) / N * H

    def gap(i):
        """Наибольший разрыв в сечении по X, в долях полуширины тела."""
        xs = sorted(sl.get(i, []))
        if len(xs) < 8:
            return 0.0
        g = max((b - a) for a, b in zip(xs, xs[1:]))
        span = xs[-1] - xs[0]
        return g / span if span > 1e-6 else 0.0

    def torso_w(i):
        """Ширина ТОЛЬКО корпуса: руки в Т-позе отсекаются полосой у оси."""
        xs = [x for x in sl.get(i, []) if abs(x) < 0.22 * H]
        return (max(xs) - min(xs)) if len(xs) > 6 else 0.0

    # ПАХ: снизу вверх — первая высота, где ноги слились (разрыв исчез)
    crotch_i = int(N * 0.50)
    for i in range(int(N * 0.20), int(N * 0.70)):
        if gap(i) < 0.06 and gap(i - 1) >= 0.06:
            crotch_i = i
            break
    # ПЛЕЧИ: выше паха, где ширина корпуса наибольшая
    sh_i = max(range(crotch_i + int(N * 0.10), int(N * 0.92)), key=torso_w)
    # ШЕЯ: над плечами ширина корпуса минимальна
    neck_i = min(range(sh_i + 2, int(N * 0.96)), key=torso_w)

    lm = {
        "Y_ANKLE": lo + 0.055 * H,
        "Y_KNEE": lo + (z_of(crotch_i) - lo) * 0.53,   # колено — чуть выше середины бедра
        "Y_CROTCH": z_of(crotch_i),
        "Y_WAIST": z_of(crotch_i) + (z_of(sh_i) - z_of(crotch_i)) * 0.42,
        "Y_SHOULDER": z_of(sh_i),
        "Y_CHIN": z_of(neck_i) + 0.018 * H,
        "Y_TOP": hi,
    }
    # ПРОВЕРКА ПОРЯДКА. Замер, который дал колено выше паха, обязан кричать, а
    # не молча уехать в крой.
    order = ["Y_ANKLE", "Y_KNEE", "Y_CROTCH", "Y_WAIST", "Y_SHOULDER",
             "Y_CHIN", "Y_TOP"]
    for a, b in zip(order, order[1:]):
        if not lm[a] < lm[b]:
            print("[замер] ПОРЯДОК НАРУШЕН: %s %.3f не ниже %s %.3f"
                  % (a, lm[a], b, lm[b]))
    return lm


def svc(name):
    return importlib.import_module("%s.services.%s" % (ADDON, name))


def build(skip_clothes=False, pheno=None, bare=False, skip_shape=False,
          face_anim=True):
    """Собрать героя.

    pheno — заменить крупные ползунки, bare — только тело со скелетом (без
    глаз, волос, кожи и одежды): так подбирается фигура перебором,
    skip_shape — не применять точную подгонку SHAPE (нужно самому подгонщику,
    иначе он будет подгонять уже подогнанное).
    """
    bpy.ops.preferences.addon_enable(module=ADDON)
    for o in list(bpy.data.objects):
        bpy.data.objects.remove(o, do_unlink=True)
    HumanService = svc("humanservice").HumanService

    # РОСТ ЗАДАЁТСЯ ПАРАМЕТРОМ, А НЕ МАСШТАБОМ ОБЪЕКТА. Здесь стояло
    # body.scale = k, и это порвало персонажа на ходу: у тела оказался
    # масштаб 1.0135, а у скелета 1.0, и при деформации сетка разъезжалась —
    # торс уезжал, ноги растягивались в невидимое, стопы отваливались.
    # Обнаружилось замером: длины костей при движении сохранялись до
    # миллиметра, то есть скелет был исправен, а рвалась именно привязка.
    # У MakeHuman рост — один из макропараметров, им и надо пользоваться.
    body = HumanService.create_human(macro_detail_dict=dict(pheno or PHENOTYPE))
    bpy.context.view_layer.update()
    print("[герой] тело: вершин %d, рост %.3f м (масштаб объекта %.3f)"
          % (len(body.data.vertices), body.dimensions.z, body.scale.z))

    # ТОЧНАЯ ПОДГОНКА ИДЁТ ДО СКЕЛЕТА. Кости считаются по форме тела один раз,
    # при постановке скелета, и за ключами формы потом не следуют. Если
    # подогнать фигуру после — плечи разъедутся с суставами.
    if not skip_shape:
        import fit_body
        for name, v in (list(SHAPE.items()) + list(MUSCLE.items())
                        + list(FACE_SHAPE.items())):
            fit_body._apply(body, name, v)
        bpy.context.view_layer.update()
        print("[герой] сложение по промерам: %d целей, мышцы: %d, голова: %d"
              % (len(SHAPE), len(MUSCLE), len(FACE_SHAPE)))

    # СКЕЛЕТ СТАВИТСЯ ДО ОДЕЖДЫ И ЧАСТЕЙ ТЕЛА. В прошлом заходе он шёл
    # последним, и всё надетое осталось без привязки: на прогоне одетая
    # фигура стояла на месте, а голое тело уходило вперёд.
    arm = add_rig(body)

    for kind, rel in ([] if bare else PARTS):
        p = os.path.join(DATA, rel)
        if not os.path.exists(p):
            print("[герой] НЕТ %-10s %s" % (kind, rel))
            continue
        HumanService.add_mhclo_asset(p, body, asset_type=kind,
                                     material_type='MAKESKIN')
        print("[герой] надето: %-10s %s" % (kind, os.path.basename(rel)))

    sp = os.path.join(DATA, SKIN)
    if os.path.exists(sp) and not bare:
        # ENHANCED_SSS — шейдер кожи самого MPFB поверх фотоскана. Рассеяние
        # текстура содержать не может: это свойство объёма, а не поверхности.
        HumanService.set_character_skin(sp, body, skin_type='ENHANCED_SSS')
        print("[герой] кожа: %s" % os.path.basename(SKIN))
    else:
        print("[герой] НЕТ кожи:", SKIN)

    # МУЖСКОЙ ПАХ ОТДЕЛЬНОЙ СЕТКОЙ. У базовой сетки MakeHuman этой геометрии
    # нет ни у мужчины, ни у женщины (проверено замером: при поле 0.0 и 1.0
    # выступ одинаков, 120 и 119 мм), а цели penis-* рассчитаны на накладку,
    # которой нет ни в одном открытом паке — просмотрены все шесть bodyparts
    # и системный набор MakeHuman (517 файлов). Поэтому строим сами.
    if not bare:
        import anatomy
        # ПОРЯДОК: сначала сосок, потом мышца. Мышца привязывается к соску —
        # брюшко идёт ему навстречу, — а сосок к мышце не привязан вовсе.
        # рельеф грудных ставится ДО скелета не обязательно, но до одежды —
        # обязательно: бельё и рубаха шьются по готовой форме тела
        anatomy.nipples(body)
        anatomy.pectorals(body)

    # ЛИЦО: РЕЧЬ, МИМИКА, ВЗГЛЯД. Ставится ПОСЛЕ частей тела: ключи с тела
    # переносятся на зубы, язык, глаза, брови и ресницы, а для этого они уже
    # должны быть надеты. Отключаемо, потому что это 89 ключей формы на 19158
    # вершин — для дальнего плана и для тех прогонов, где лицо не нужно,
    # лишний вес.
    if face_anim and not bare:
        import face as face_mod
        face_mod.load(body)
        eyes = next((o for o in bpy.data.objects
                     if o.type == 'MESH' and "high-poly" in o.name), None)
        if arm is not None and eyes is not None:
            face_mod.add_eye_bones(body, arm, eyes)
    # ПАХ СТАВИТСЯ ТОЛЬКО РАЗДЕТОМУ. Под одеждой его не видно никогда, а в
    # кадре он проступал светлым пятном между полами пальто: накладка сидит
    # ближе к телу, чем штаны, но их смещение по нормали в паху сходится в
    # ноль — там поверхность вогнутая. Одетому он лишний и по весу (378 вершин
    # и отдельный материал), и по виду.
    if not bare and arm is not None and skip_clothes:
        anatomy.add_mesh(body, arm)

    if not skip_clothes and not bare:
        wardrobe(body)

    n = sum(len(o.data.vertices) for o in bpy.data.objects if o.type == 'MESH')
    print("[герой] всего вершин: %d, объектов: %d"
          % (n, len([o for o in bpy.data.objects if o.type == 'MESH'])))
    return body


