#!/usr/bin/env python3
"""ПОРТНОВСКИЙ МЕТР ДЛЯ ГЕРОЯ: обмер тела и сверка с настоящими людьми.

ЗАЧЕМ. Про фигуру нельзя спорить словами. «Выглядит подростком» — верное
наблюдение, но чинить по нему нечего: непонятно, что именно узко и насколько.
Поэтому тело обмеряется как у портного и сравнивается с базой РЕАЛЬНЫХ
измерений живых людей.

БАЗА: ANSUR II (Anthropometric Survey of US Army Personnel, 2012) — 93 промера
у 4082 мужчин и 1986 женщин, открытые данные, скачаны и посчитаны нами, а не
пересказаны по памяти. Средний мужчина: рост 1756 мм, плечи между суставами
416, по дельтам 510, обхват груди 1059, талии 941, бедра 625, голени 392,
шеи 398, высота плеча 1441, промежности 846, колена 488, длина плеча 335,
предплечья 268, обхват головы 574.

ОГОВОРКА, КОТОРУЮ НАДО ДЕРЖАТЬ В ГОЛОВЕ: ANSUR — это солдаты 2012 года,
средний вес 85.5 кг. Крестьянин 1894 года суше. Поэтому цель у нас не
«средний по ANSUR»: КОСТЬ (длины, высоты, ширина плеч) как в базе, а ОБХВАТЫ
мягких тканей заметно меньше. В таблице ниже видно и то и другое.

ВЫСОТЫ ПРОМЕРОВ БЕРУТСЯ ИЗ ТОЙ ЖЕ БАЗЫ, А НЕ НА ГЛАЗ. Первая версия этого
файла ставила уровни долями роста от балды, и «обхват шеи» попал на трапецию
(+55%), а «голень» на колено (+34%). Теперь грудь мерится на 0.735 роста,
талия на 0.602, колено на 0.278 — это средние высоты соответствующих
ориентиров по ANSUR.

КАК МЕРЯЕТСЯ ОБХВАТ. Сечение тела на нужной высоте, проекция на пол, выпуклая
оболочка, её периметр. Оболочка чуть завышает там, где тело вогнуто; на
человеке это единицы процентов и это честнее, чем считать периметр по всем
точкам подряд, где любая складка добавит длины.
РУКИ ИСКЛЮЧАЮТСЯ ПО ВЕСАМ — иначе они попадут в обхват груди.

ВАЖНО ПРО ПОЗУ: базовая сетка MPFB стоит НЕ в Т-позе, а в А-позе — руки
опущены примерно на 45°. Поэтому размах рук по габариту не мерится вовсе
(вышло бы 995 мм вместо 1750), и длины рук берутся по костям.
"""
import math

import bpy

# доля роста: (ANSUR II мужчины, наша цель для крестьянина)
TARGET = {
    "рост":             (1.0000, 1.0000),
    "высота плеча":     (0.8204, 0.8200),
    "высота промежн.":  (0.4817, 0.4850),
    "высота колена":    (0.2781, 0.2790),
    "плечи по кости":   (0.2367, 0.2380),
    "плечи по дельтам": (0.2906, 0.2850),
    "длина плеча":      (0.1909, 0.1909),
    "длина предплечья": (0.1525, 0.1525),
    "обхват груди":     (0.6028, 0.5800),
    "обхват талии":     (0.5356, 0.4900),
    "обхват бедра":     (0.3560, 0.3300),
    "обхват голени":    (0.2234, 0.2150),
    "обхват таза":      (0.5805, 0.5500),
    "обхват шеи":       (0.2264, 0.2200),
    "обхват головы":    (0.3271, 0.3271),
}
# высоты ориентиров в долях роста (ANSUR II)
Z_CHEST, Z_WAIST, Z_HIP = 0.7352, 0.6016, 0.5300
# СПРАВОЧНЫЕ ПРОМЕРЫ: печатаются, но в счёт промахов не идут, потому что у нас
# и у ANSUR они означают РАЗНОЕ, и разницу не убрать подгонкой.
#   «плечи по дельтам» — у нас рука висит под 45°, и в срез на высоте сустава
#     попадает часть плеча; число завышено на постоянную величину.
#   «длина плеча», «длина предплечья» — у нас это кости от сустава до сустава,
#     у ANSUR промеры между костными выступами на поверхности (акромион,
#     радиале, стилион). Локоть у MakeHuman сидит ниже радиале, поэтому плечо
#     выходит короче, а предплечье длиннее. Судить надо по СУММЕ — по ней и
#     ведётся подгонка, и признак у неё независимый: запястье должно
#     приходиться на высоту промежности.
INFO = ("плечи по дельтам", "длина плеча", "длина предплечья")
ARM_OUT = ("ForeArm", "Hand", "Finger", "Thumb")   # что выкинуть из торса
ARM_ALL = ARM_OUT + ("Shoulder", "Arm")


def _hull(pts):
    p = sorted(set(pts))
    if len(p) < 3:
        return p

    def half(seq):
        out = []
        for q in seq:
            while len(out) >= 2 and \
                    (out[-1][0] - out[-2][0]) * (q[1] - out[-2][1]) - \
                    (out[-1][1] - out[-2][1]) * (q[0] - out[-2][0]) <= 0:
                out.pop()
            out.append(q)
        return out
    return half(p)[:-1] + half(list(reversed(p)))[:-1]


def _perim(pts):
    h = _hull(pts)
    if len(h) < 3:
        return 0.0
    return sum(math.dist(a, b) for a, b in zip(h, h[1:] + h[:1]))


def _band(verts, z, half=0.006):
    return [(v.x, v.y) for v in verts if abs(v.z - z) < half]


def measure(body, arm):
    # МЕРЯЕМ ВЫЧИСЛЕННУЮ СЕТКУ, А НЕ ИСХОДНУЮ. В базовой сетке MakeHuman есть
    # служебная оболочка-помощник: редкая клетка вокруг тела, по которой
    # подгоняется одежда. В кадре её нет — её выбрасывает маска, — но в
    # body.data она лежит, и первый обмер считал именно её: «обхват шеи»
    # получился 577 мм при норме 384, «голень» 603 при 379. Числа были
    # чудовищные и правдоподобные одновременно, потому что мерился реальный
    # объект — просто не тот.
    dg = bpy.context.evaluated_depsgraph_get()
    ev = body.evaluated_get(dg)
    me = ev.to_mesh()
    M = body.matrix_world
    idx_out = {g.index for g in body.vertex_groups
               if any(a in g.name for a in ARM_OUT)}
    idx_all = {g.index for g in body.vertex_groups
               if any(a in g.name for a in ARM_ALL)}
    torso, no_arms, allv, right = [], [], [], []
    for v in me.vertices:
        p = M @ v.co
        allv.append(p)
        w_out = sum(g.weight for g in v.groups if g.group in idx_out)
        w_all = sum(g.weight for g in v.groups if g.group in idx_all)
        if w_out < 0.5:
            no_arms.append(p)          # торс с дельтами, без предплечий
        if w_all < 0.5:
            torso.append(p)            # чистый торс
            if p.x > 0.02:
                right.append(p)
    ev.to_mesh_clear()
    zs = [p.z for p in allv]
    lo, hi = min(zs), max(zs)
    H = hi - lo
    b = arm.data.bones
    out = {"рост": H}

    def bz(n):
        return b[n].head_local.z - lo if n in b else None

    if "LeftArm" in b and "RightArm" in b:
        out["плечи по кости"] = (b["LeftArm"].head_local -
                                 b["RightArm"].head_local).length
        out["высота плеча"] = bz("LeftArm")
        out["длина плеча"] = b["LeftArm"].length
    if "LeftForeArm" in b:
        out["длина предплечья"] = b["LeftForeArm"].length
    if "LeftLeg" in b:
        out["высота колена"] = bz("LeftLeg")

    # ПРОМЕЖНОСТЬ ПО РАЗРЫВУ, а не по кости: ниже неё сечение распадается на
    # две ноги. Кость таза стоит выше настоящей промежности сантиметра на три.
    crotch = 0.48 * H
    for i in range(int(H * 1000 * 0.35), int(H * 1000 * 0.62)):
        z = lo + i / 1000.0
        xs = sorted(p.x for p in allv if abs(p.z - z) < 0.004)
        if len(xs) < 8:
            continue
        gap = max((q - p) for p, q in zip(xs, xs[1:]))
        if gap < 0.02:
            crotch = z - lo
            break
    out["высота промежн."] = crotch

    # ПЛЕЧИ ПО ДЕЛЬТАМ: самое широкое место на уровне сустава плеча, дельты
    # оставляем, предплечья убираем
    zsh = out.get("высота плеча", 0.82 * H)
    band = [p for p in no_arms if abs(p.z - (lo + zsh)) < 0.025]
    if band:
        out["плечи по дельтам"] = max(p.x for p in band) - min(p.x for p in band)

    out["обхват груди"] = _perim(_band(torso, lo + Z_CHEST * H))
    out["обхват талии"] = _perim(_band(torso, lo + Z_WAIST * H))
    # ТАЗ на высоте вертела (0.53 роста): ниже уже начинаются ноги врозь
    out["обхват таза"] = _perim(_band(torso, lo + Z_HIP * H))
    # ШЕЯ: самое узкое место между плечами и головой
    if "Neck" in b and "Head" in b:
        z0, z1 = b["Neck"].head_local.z, b["Head"].head_local.z
        cand = [(_perim(_band(torso, z0 + (z1 - z0) * t, 0.004)), t)
                for t in (0.2, 0.35, 0.5, 0.65, 0.8)]
        cand = [c for c in cand if c[0] > 0.05]
        if cand:
            out["обхват шеи"] = min(cand)[0]
    # ГОЛОВА: самое широкое сечение выше подбородка
    if "Head" in b:
        zh = b["Head"].head_local.z
        out["обхват головы"] = max(
            _perim(_band(allv, zh + d, 0.006)) for d in (0.04, 0.06, 0.08, 0.10))
    # БЕДРО сразу под промежностью, ГОЛЕНЬ — самое толстое между коленом и щиколоткой
    out["обхват бедра"] = _perim(_band(right, lo + crotch - 0.03))
    if "LeftLeg" in b and "LeftFoot" in b:
        z0, z1 = b["LeftFoot"].head_local.z, b["LeftLeg"].head_local.z
        out["обхват голени"] = max(
            _perim(_band(right, z0 + (z1 - z0) * t)) for t in (0.35, 0.45, 0.55, 0.65))
    return out


def report(body, arm, note=""):
    m = measure(body, arm)
    H = m["рост"]
    print("=" * 76)
    print("ОБМЕР ТЕЛА %s (рост %.3f м)" % (note, H))
    print("  %-18s %7s %7s %7s   %s" %
          ("промер", "у нас", "цель", "ANSUR", "отклонение от цели"))
    bad = []
    for k, (ansur, want) in TARGET.items():
        if m.get(k) is None:
            continue
        got, tgt = m[k], want * H
        d = (got - tgt) / tgt * 100 if tgt else 0
        info = k in INFO
        mark = "  (справочно)" if info else \
            ("" if abs(d) < 6 else ("  — УЖЕ" if d < 0 else "  — ШИРЕ"))
        if abs(d) >= 6 and not info:
            bad.append((abs(d), k, d))
        print("  %-18s %6.0f %7.0f %7.0f   %+6.1f%%%s"
              % (k, got * 1000, tgt * 1000, ansur * H * 1000, d, mark))
    bad.sort(reverse=True)
    print("  промахов больше 6%%: %d из %d%s"
          % (len(bad), len(TARGET) - len(INFO),
             (" — худшие: " + ", ".join("%s %+.0f%%" % (k, d)
                                        for _, k, d in bad[:3])) if bad else ""))
    print("=" * 76)
    return m
