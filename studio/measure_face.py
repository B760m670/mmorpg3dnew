def _mat_index(body, needle):
    for i, m in enumerate(body.data.materials):
        if m is not None and needle in m.name.lower():
            return i
    return None


def _by_material(body, needle):
    """Вершины многоугольников с этим материалом, в мире, по ВЫЧИСЛЕННОЙ сетке."""
    idx = _mat_index(body, needle)
    if idx is None:
        return []
    dg = bpy.context.evaluated_depsgraph_get()
    ev = body.evaluated_get(dg)
    me = ev.to_mesh()
    M = body.matrix_world
    out = []
    for p in me.polygons:
        if p.material_index == idx:
            out += [M @ me.vertices[i].co for i in p.vertices]
    ev.to_mesh_clear()
    return out


def _all(body):
    dg = bpy.context.evaluated_depsgraph_get()
    ev = body.evaluated_get(dg)
    me = ev.to_mesh()
    M = body.matrix_world
    pts = [M @ v.co for v in me.vertices]
    ev.to_mesh_clear()
    return pts


def _perim(pts):
    """Периметр выпуклой оболочки набора точек в плоскости xy."""
    P = sorted(set((round(p.x, 5), round(p.y, 5)) for p in pts))
    if len(P) < 3:
        return 0.0

    def half(seq):
        h = []
        for p in seq:
            while len(h) >= 2:
                (x1, y1), (x2, y2) = h[-2], h[-1]
                if (x2 - x1) * (p[1] - y1) - (y2 - y1) * (p[0] - x1) > 0:
                    break
                h.pop()
            h.append(p)
        return h
    hull = half(P)[:-1] + half(P[::-1])[:-1]
    return sum(((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2) ** 0.5
               for a, b in zip(hull, hull[1:] + hull[:1]))


def midline_profile(body, step=0.002):
    """Профиль средней линии лица: для каждой высоты — самая передняя точка.

    Нужен, чтобы найти ПОДБОРОДОК. Первый заход брал «самую нижнюю точку
    средней линии головы», а областью головы считалось всё выше макушки минус
    270 мм — то есть шея и верх груди. Подбородок уезжал на 40 мм вниз, в шею,
    и вместе с ним все промеры, отсчитанные от него. Ширина головы вышла
    302 мм при человеческих 154 — невозможное число, по нему и поймал.
    """
    pts = _all(body)
    top = max(p.z for p in pts)
    prof = []
    z = top - 0.06
    while z > top - 0.34:
        band = [p for p in pts if abs(p.x) < 0.008 and abs(p.z - z) < step
                and p.y < 0]
        if band:
            prof.append((z, min(p.y for p in band)))
        z -= step
    return prof


CHIN_BACK = 0.008        # на сколько подбородок отступает назад под собой


def chin_by_normal(body):
    """Подбородок по НАПРАВЛЕНИЮ ПОВЕРХНОСТИ.

    Признак местный и от общей формы не зависит: у гнатиона поверхность
    смотрит строго ВНИЗ, выше по подбородку — вниз-вперёд, ниже, на шее, —
    вперёд. Ищем среди срединных вершин под ртом ту, у которой нормаль
    ближе всего к вертикали вниз.
    """
    lips = _by_material(body, "lip")
    if not lips:
        return None
    z_mouth = sum(p.z for p in lips) / len(lips)
    M = body.matrix_world
    R = M.to_3x3()
    best = None
    for v in body.data.vertices:
        p = M @ v.co
        if abs(p.x) > 0.010 or p.y > 0:
            continue
        if not (z_mouth - 0.075 < p.z < z_mouth - 0.010):
            continue
        n = (R @ v.normal).normalized()
        if best is None or n.z < best[0]:
            best = (n.z, p.z)
    return best[1] if best else None


def chin_by_bone(body):
    """Подбородок по ВЕСОВОЙ ГРУППЕ КОСТИ ГОЛОВЫ.

    ТРЕТИЙ СПОСОБ, И ОН НЕ ГАДАЕТ. Два предыдущих искали подбородок по изгибу
    профиля: сперва «самый большой отступ назад» (ломался на подгубной
    складке), потом «отступ на 12 мм под погонионом» (ломался, как только
    подбородок укорачивали — отступ переставал набираться, и опора уезжала на
    шею: высота головы 328-338 мм при человеческих 231).
    Общая беда обоих: они выводят анатомию из формы, а форму мы как раз и
    меняем. Значит опору надо брать оттуда, где она не зависит от формы.
    У скелета есть кость головы, и её весовая группа кончается ровно там, где
    голова переходит в шею. Это и есть граница — её знает привязка, а не изгиб.
    Тот же приём, что с ушами и губами: брать по материалу, а не по высоте.
    """
    g = body.vertex_groups.get("Head")
    if g is None:
        return None
    dg = bpy.context.evaluated_depsgraph_get()
    M = body.matrix_world
    zs = []
    for v in body.data.vertices:
        if abs(v.co.x) > 0.010:
            continue
        for e in v.groups:
            if e.group == g.index and e.weight > 0.5:
                p = M @ v.co
                if p.y < 0:                 # передняя половина: не затылок
                    zs.append(p.z)
                break
    return min(zs) if zs else None


def chin_z(body):
    """Высота подбородка (гнатион), устойчиво.

    ВТОРОЙ ЗАХОД. Первый брал «самый большой отступ назад» на всём профиле —
    и оказался ломким: под нижней губой отступ почти такой же, как под
    подбородком, и победитель менялся от мелочи. Одно и то же тело мерилось
    то на 118 мм, то на 106.
    Теперь так: сперва находим САМУЮ ПЕРЕДНЮЮ точку подбородка (погонион) —
    это выступ ниже рта, — а гнатион ищем под ней: там, где поверхность
    отступила назад больше чем на 12 мм. Обе опоры устойчивы, потому что
    выступ подбородка на профиле один и ни с чем не спорит.
    """
    # ЧЕТВЁРТЫЙ ЗАХОД, И ОН ПРОВЕРЕН, А НЕ ПРИНЯТ ПО КРАСОТЕ ЗАМЫСЛА.
    # Способ «по весовой группе кости головы» звучал безупречно — границу
    # головы и шеи знает привязка, а не изгиб, — и дал 1.434 вместо 1.500,
    # то есть промахнулся на 66 мм: у MakeHuman веса головы плавно затухают
    # ВНИЗ ПО ШЕЕ, и «вес больше половины» кончается сильно ниже челюсти.
    # Оставляю его запасным: он не срывается никогда, а профильный способ
    # точнее, пока подбородок вообще находится.
    prof = midline_profile(body)
    if len(prof) < 8:
        return None
    # кончик носа — самая передняя точка всего профиля
    i_nose = min(range(len(prof)), key=lambda i: prof[i][1])
    below = prof[i_nose:]
    if len(below) < 6:
        return None
    # рот — самая ЗАДНЯЯ точка под носом; подбородок ищем уже под ртом
    i_mouth = max(range(len(below)), key=lambda i: below[i][1])
    lower = below[i_mouth:]
    if len(lower) < 4:
        lower = below
    # погонион: самая передняя точка ниже рта
    i_pog = min(range(len(lower)), key=lambda i: lower[i][1])
    y_pog, z_pog = lower[i_pog][1], lower[i_pog][0]
    # ТРЕТИЙ ЗАХОД, И ПРИЧИНА ЕГО ПОУЧИТЕЛЬНА. Прежний запасной выход возвращал
    # ДНО просмотренной полосы, если отступ назад на 12 мм не встречался. Пока
    # подбородок был длинный, отступ встречался всегда, и запасной выход молчал.
    # Стоило начать перебирать chin-height в меньшую сторону — отступ перестал
    # набираться, и опора уехала на ШЕЮ: высота головы 330 мм при человеческих
    # 231, ширина скул 417 мм (это уже плечи). Четыре точки перебора из пяти
    # оказались мусором, и мусор был правдоподобно оформлен.
    # Теперь: ищем отступ только в 60 мм под погонионом — ниже подбородка не
    # бывает, — а если он там не набрался, берём самую отступившую точку в этой
    # же полосе. Дно профиля больше не возвращается никогда.
    # ПОЛОСА 35 ММ, А НЕ 60. При 60 мм «самая отступившая точка» оказывалась
    # просто дном полосы — под подбородком поверхность отступает монотонно, и
    # чем глубже смотришь, тем «лучше» ответ. Ниже погониона подбородок не
    # уходит и на 35 мм: у человека рот-подбородок 50 мм ВСЕГО, а погонион
    # лежит между ними.
    полоса = [(z, y) for z, y in lower[i_pog:] if z > z_pog - 0.035]
    for z, y in полоса:
        if y - y_pog > CHIN_BACK:
            return z
    if полоса:
        return max(полоса, key=lambda p: p[1] - y_pog)[0]
    return z_pog


def chin(body):
    """Подбородок с САМОПРОВЕРКОЙ и запасными способами.

    ПЯТЬ ЗАХОДОВ, И ЧЕТЫРЕ ИЗ НИХ ДАВАЛИ ПРАВДОПОДОБНОЕ И НЕВЕРНОЕ:
      1. «самый большой отступ назад» — ловился на подгубной складке,
         одно тело меряло то 118 мм, то 106;
      2. «отступ 12 мм под погонионом» — рассыпался, стоило укоротить
         подбородок: опора уезжала на шею, высота головы 328 мм при 231;
      3. «по весовой группе кости головы» — замысел безупречен (границу знает
         привязка, а не изгиб), а промах 66 мм: веса головы затухают вниз по
         шее, и «вес больше половины» кончается ниже челюсти;
      4. полоса 60 мм под погонионом — «самая отступившая точка» оказывалась
         просто дном полосы, потому что под подбородком поверхность отступает
         монотонно.
    Общая беда всех четырёх: они выводят опору ИЗ ФОРМЫ, а форму мы как раз и
    меняем. Пока форма была прежней, они молчали; менялась — врали.
    Поэтому здесь не один способ, а проверка: считаем высоту головы и, если
    она вне человеческих 195–265 мм, берём следующий способ. Врать молча
    больше нечему.
    """
    pts = _all(body)
    top = max(p.z for p in pts)
    for сп in (chin_z, chin_by_normal, chin_by_bone):
        z = сп(body)
        if z is None:
            continue
        if 0.195 <= top - z <= 0.265:
            return z, сп.__name__
    z = chin_z(body)
    return z, "НИ ОДИН СПОСОБ НЕ ДАЛ ЧЕЛОВЕЧЕСКОЙ ГОЛОВЫ"


def трети(body, z_chin):
    """Высоты подносовой точки и рта — для деления лица на трети.

    ЗАЧЕМ. Заказчик сказал: лицо вытянутое, подбородок длинный. Лицевой
    указатель (высота лица к ширине скул) при этом лежал в норме — 84.5 при
    84–88. Противоречия нет: указатель говорит, УЗКОЕ ли лицо в целом, и
    ничего не говорит о том, КАК высота распределена сверху вниз. Длинный
    подбородок при нормальной общей высоте лица даёт короткий лоб и середину,
    а указатель этого не видит вовсе.

    Нормы (Farkas, мужчины европейского происхождения, мм):
      переносица-подносовая  54.8      подносовая-подбородок  72.6
      подносовая-рот         22.0      рот-подбородок         50.6
    Отсюда доли: нижняя треть 72.6/122.6 = 0.592 всей высоты лица,
    подбородок 50.6/72.6 = 0.697 нижней трети.
    """
    prof = midline_profile(body)
    if len(prof) < 8:
        return None, None
    i_nose = min(range(len(prof)), key=lambda i: prof[i][1])
    # РОТ БЕРЁТСЯ ПО МАТЕРИАЛУ ГУБ, а не по профилю: на профиле «самая задняя
    # точка под носом» может оказаться и подгубной складкой.
    lips = _by_material(body, "lip")
    z_mouth = (sum(p.z for p in lips) / len(lips)) if lips else None
    # ПОДНОСОВАЯ ИЩЕТСЯ В ПОЛОСЕ ПОД САМИМ НОСОМ, а не «где-то выше рта».
    # Первый заход брал самую заднюю точку между кончиком носа и СРЕДНЕЙ
    # высотой губ — и находил не подносовую, а складку над верхней губой:
    # подносовая выходила ровно на уровне рта, доля подбородка 0.982 при норме
    # 0.697. Число было неправдоподобным, и по нему ошибка и поймалась.
    # У человека подносовая лежит на 20-30 мм ниже кончика носа, туда и смотрим.
    z_nose = prof[i_nose][0]
    низ = [(z, y) for z, y in prof if z_nose - 0.030 < z < z_nose - 0.008]
    z_sn = max(низ, key=lambda p: p[1])[0] if len(низ) >= 2 else None
    return z_sn, z_mouth


def measure(body, eyes=None):
    pts = _all(body)
    zs = [p.z for p in pts]
    top, H = max(zs), max(zs) - min(zs)
    ears = _by_material(body, "ear")
    lips = _by_material(body, "lip")
    ear_ids = set((round(p.x, 6), round(p.y, 6), round(p.z, 6)) for p in ears)
    m = {}

    z_chin, способ = chin(body)
    if z_chin is None:
        z_chin = top - 0.23
    m["_способ"] = способ
    # ГОЛОВА — ЭТО ОТ ПОДБОРОДКА ВВЕРХ, и ни миллиметром ниже: там шея.
    head = [p for p in pts if p.z >= z_chin]
    head_noears = [p for p in head
                   if (round(p.x, 6), round(p.y, 6), round(p.z, 6)) not in ear_ids]
    m["_подбородок"] = z_chin
    m["высота головы"] = top - z_chin

    # ПЕРЕНОСИЦА: самая задняя точка средней линии МЕЖДУ кончиком носа и лбом.
    prof = midline_profile(body)
    if prof:
        # кончик носа — самая передняя точка профиля
        zt = min(prof, key=lambda p: p[1])[0]
        above = [(z, y) for z, y in prof if zt < z < zt + 0.055]
        if above:
            zb = max(above, key=lambda p: p[1])[0]
            m["лицо: нос-подбородок"] = zb - z_chin

    # ЧЕРЕПНАЯ КОРОБКА: только выше глаз, иначе в срез лезут челюсть и шея
    crown = [p for p in head_noears if p.z > z_chin + 0.085]
    if crown:
        m["ширина головы"] = max(p.x for p in crown) - min(p.x for p in crown)
        m["длина головы"] = max(p.y for p in crown) - min(p.y for p in crown)

    # СКУЛЫ: самое широкое место лица без ушей, ищем по полосам, а не наугад
    best = 0.0
    zz = z_chin + 0.045
    while zz < z_chin + 0.100:
        band = [p for p in head_noears if abs(p.z - zz) < 0.006]
        if len(band) > 6:
            best = max(best, max(p.x for p in band) - min(p.x for p in band))
        zz += 0.004
    if best:
        m["ширина скул"] = best

    # ОБХВАТ ГОЛОВЫ: срез над бровями, уши включены — так мерят и в ANSUR
    zz = z_chin + 0.115
    band = [p for p in head if abs(p.z - zz) < 0.008]
    if len(band) > 8:
        m["обхват головы"] = _perim(band)

    if ears:
        L = [p for p in ears if p.x > 0]
        if L:
            m["длина уха"] = max(p.z for p in L) - min(p.z for p in L)
            m["ширина уха"] = max(p.y for p in L) - min(p.y for p in L)
            m["ухо-макушка"] = top - (sum(p.z for p in L) / len(L))
            m["_вершин уха"] = len(L)

    if lips:
        m["ширина рта"] = max(p.x for p in lips) - min(p.x for p in lips)

    # ШИРИНА ЧЕЛЮСТИ (бигониальная). В ANSUR II её нет, поэтому норма взята из
    # лицевой антропометрии (Farkas, мужчины): go-go 97.1 мм при zy-zy 137.1,
    # то есть челюсть составляет 0.71 ширины скул. Сужение лица книзу —
    # НОРМА, вопрос только в мере: при 0.6 лицо сходится клином.
    # Меряем в полосе чуть выше подбородка, уши исключены.
    best = 0.0
    zz = z_chin + 0.012
    while zz < z_chin + 0.045:
        band = [p for p in head_noears if abs(p.z - zz) < 0.005]
        if len(band) > 6:
            best = max(best, max(p.x for p in band) - min(p.x for p in band))
        zz += 0.004
    if best:
        m["ширина челюсти"] = best

    z_sn, z_mouth = трети(body, z_chin)
    z_nas = m.get("лицо: нос-подбородок")
    if z_sn is not None and z_nas:
        m["_подносовая"] = z_sn
        m["нижняя треть"] = (z_sn - z_chin) / z_nas
        if z_mouth is not None and z_sn > z_chin:
            m["подбородок в трети"] = (z_mouth - z_chin) / (z_sn - z_chin)

    if eyes is not None:
        dg = bpy.context.evaluated_depsgraph_get()
        ev = eyes.evaluated_get(dg)
        em = ev.to_mesh()
        Me = eyes.matrix_world
        ep = [Me @ v.co for v in em.vertices]
        ev.to_mesh_clear()
        L = [p for p in ep if p.x > 0]
        R = [p for p in ep if p.x < 0]
        if L and R:
            cl = sum(L, Vector()) / len(L)
            cr = sum(R, Vector()) / len(R)
            m["межзрачковое"] = (cl - cr).length
    m["_рост"] = H
    return m


def report(body, eyes=None, note=""):
    m = measure(body, eyes)
    H = m["_рост"]
    print("\n=== ГОЛОВА И ЛИЦО %s (рост %.3f м) ===" % (note, H))
    # САМОПРОВЕРКА ИНСТРУМЕНТА: если подбородок или высота головы вышли
    # неправдоподобными, всё остальное считать нельзя — оно от них отсчитано.
    hh = m.get("высота головы", 0) * 1000
    if not 195 <= hh <= 265:
        print("  !!! ОПОРА НЕ НАЙДЕНА: высота головы %.0f мм при человеческих "
              "195-265. Всё, что ниже, отсчитано от неверного подбородка и "
              "читать это нельзя." % hh)
    print("  опоры: подбородок z=%.3f (%s), высота головы %.0f мм "
          "(у человека около %.0f), вершин уха %d"
          % (m.get("_подбородок", 0), m.get("_способ", "?"),
             m.get("высота головы", 0) * 1000,
             0.1333 * H * 1000, m.get("_вершин уха", 0)))
    print("  %-22s %8s %8s %8s" % ("промер", "наше", "норма", "промах"))
    bad = []
    for k, (frac, mm) in TARGET.items():
        if k not in m:
            print("  %-22s %8s   не снялся" % (k, "—"))
            continue
        got, tgt = m[k] * 1000, frac * H * 1000
        d = (got - tgt) / tgt * 100
        mark = "" if abs(d) < 6 else ("  — МЕНЬШЕ" if d < 0 else "  — БОЛЬШЕ")
        if abs(d) >= 6:
            bad.append((abs(d), k, d))
        print("  %-22s %8.1f %8.1f %+7.1f%%%s" % (k, got, tgt, d, mark))
    for k, mm in TARGET_OTHER.items():
        if k in m:
            tgt = mm * H / 1.756
            got = m[k] * 1000
            print("  %-22s %8.1f %8.1f %+7.1f%%   (не ANSUR)"
                  % (k, got, tgt, (got - tgt) / tgt * 100))
    print("  %-22s %8s %8s %8s" % ("отношение", "наше", "норма", "разброс"))
    for k, ((a, b), tgt, (lo, hi)) in ОТНОШЕНИЯ.items():
        if a not in m or b not in m or not m[b]:
            print("  %-22s %8s   не снялось" % (k, "—"))
            continue
        v = m[a] / m[b] * 100.0
        mark = "" if lo <= v <= hi else ("  — УЖЕ/ВЫШЕ НОРМЫ" if v > hi
                                        else "  — ШИРЕ НОРМЫ")
        print("  %-22s %8.1f %8.1f %5.0f-%-3.0f%s" % (k, v, tgt, lo, hi, mark))
    print("  %-22s %8s %8s %8s" % ("доля", "наше", "норма", "разброс"))
    for k, (tgt, (lo, hi)) in ДОЛИ.items():
        key = k.replace(" лица", "")
        if key not in m:
            print("  %-22s %8s   не снялось" % (k, "—")); continue
        v = m[key]
        mark = "" if lo <= v <= hi else ("  — ДЛИННЕЕ НОРМЫ" if v > hi
                                         else "  — КОРОЧЕ НОРМЫ")
        print("  %-22s %8.3f %8.3f %.3f-%.3f%s" % (k, v, tgt, lo, hi, mark))
    if bad:
        bad.sort(reverse=True)
        print("  ХУЖЕ ВСЕГО: " + ", ".join("%s %+.0f%%" % (k, d) for _, k, d in bad[:4]))
    return m
