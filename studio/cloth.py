"""ТКАНЬ: перекрасить готовый ассет так, чтобы он перестал быть костюмом.

ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ tint(). Умножение на тон меняет ОБЩИЙ тон и бессильно
там, где беда в рисунке. У рубахи elvs_male_boho_top1 крой русский —
воротник-стойка, прямой стан, широкий рукав, — а роспись индийская: золотая
парча с пейсли по вороту, обшлагам и подолу. Умножь её хоть на что: пейсли
останется пейсли, а золото — золотом. Менять надо саму картинку.

ЧТО ИЗМЕРЕНО В ИСХОДНОЙ КАРТИНКЕ (1024x1024, развёртка занимает 39.8%):
  стан рубахи   — РОВНЫЙ цвет [31,31,31], без единой нитки фактуры;
                  60% площади ткани приходится на него (613 граней из 1711);
  тесьма        — всё остальное: золото с красно-чёрным пейсли.
То есть «фактура ткани» у этой рубахи существует только на тесьме, а сам стан
в кадре — крашеный пластик. Это и читается синтетикой.

КАК ПРАВИМ. Маска уже нарисована за нас: тесьма — это ровно те пиксели, что
отличаются от ровного цвета стана. Значит не нужно ни искать воротник в UV, ни
угадывать, где обшлаг: берём готовую маску и МЕНЯЕМ ЕЙ ЦВЕТ, а стану даём
настоящее полотняное переплетение.

ЦВЕТ ВЫБРАН НЕ НА ВКУС. Повседневная косоворотка городского обывателя 1890-х —
крашеный лён или ситец: индиго, реже белый. Вышивка узкая, красная по вороту,
обшлагам и подолу. Яркая красная рубаха целиком — праздничная, и на будний
день в кадре это будет ряженый.
"""
import numpy as np


def s2l(c):
    """sRGB -> линейный. Пиксели Блендера линейные, а цвета мы называем в sRGB."""
    c = np.asarray(c, dtype=np.float64)
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


ЛЁН = (0.155, 0.185, 0.275)      # индиго, крашеный лён
ВЫШИВКА = (0.36, 0.115, 0.105)   # кумач, стиранный не первый год
ОБВОДКА = (0.52, 0.48, 0.40)     # небелёная нить
ФОН = (31 / 255.0, 31 / 255.0, 31 / 255.0)   # ровный цвет стана в исходнике


def _фон(rgb, verbose=True):
    """Цвет стана — САМЫЙ ЧАСТЫЙ цвет картинки, а не заранее известное число.

    Заранее известное число меня и подвело. Читая PNG питоном, я получал
    линейные величины и брал фон как s2l([31,31,31]) = 0.0129. В Блендере тот
    же файл пришёл НЕЗАЛИНЕАРИЗОВАННЫМ, 0.1216, — маска не совпала ни с одним
    пикселем, «тесьма» стала всей картинкой, и дальше отсев крупных кусков
    съел её целиком: «стан 100%, тесьма 0%». Рубаха уехала в игру ровно-синей.

    Своего цвета стану не назначаем: 87% пикселей холста — один ровный тон, и
    самый частый цвет находит его без всяких допущений. Заодно по нему видно,
    в каком пространстве пришли пиксели.
    """
    q = np.clip((rgb * 512).round().astype(np.int64), 0, 512)
    key = (q[..., 0] * 513 + q[..., 1]) * 513 + q[..., 2]
    vals, cnt = np.unique(key.ravel(), return_counts=True)
    k = vals[np.argmax(cnt)]
    фон = np.array([(k // 513) // 513, (k // 513) % 513, k % 513]) / 512.0
    лин = abs(фон[0] - s2l(ФОН)[0]) < abs(фон[0] - ФОН[0])
    if verbose:
        print("[рубаха] фон картинки %s (%.1f%% холста), пиксели %s"
              % (np.round(фон, 4), 100 * cnt.max() / key.size,
                 "линейные" if лин else "в sRGB"))
    return фон, bool(лин)


def _box_mean(a, r):
    """Среднее в окне (2r+1). Через накопленные суммы — иначе на 1024x1024 это
    минуты. Нуль в начале добавлен НАМЕРЕННО: без него сумма по окну съезжает
    на пиксель и последняя строка выходит за границу массива."""
    def one(x):
        c = np.concatenate([np.zeros((1, x.shape[1])), np.cumsum(x, axis=0)])
        n = x.shape[0]
        lo = np.clip(np.arange(n) - r, 0, n)
        hi = np.clip(np.arange(n) + r + 1, 0, n)
        return (c[hi] - c[lo]) / (hi - lo)[:, None]
    return one(one(a).T).T


def _weave(h, w, seed=3):
    """Полотняное переплетение: две нитяные системы плюс неровность пряжи.

    Множитель, а не цвет: так один и тот же рисунок годится любому тону. Шаг
    подобран по длине: у льна 12-16 нитей на сантиметр, развёртка рубахи
    покрывает около полутора метров ткани на 1024 пикселя, то есть примерно
    7 пикселей на нить в обе стороны — оттуда шаг 7.
    """
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:h, 0:w]
    основа = 0.5 + 0.5 * np.cos(2 * np.pi * x / 7.0)
    уток = 0.5 + 0.5 * np.cos(2 * np.pi * y / 7.0)
    ткань = 1.0 + 0.085 * (основа - уток)
    # неровность пряжи: длинные полосы вдоль нити, а не белый шум
    пряжа = rng.normal(0, 1, (h, w // 7 + 1))
    пряжа = np.repeat(пряжа, 7, axis=1)[:, :w]
    ткань *= 1.0 + 0.05 * пряжа
    return np.clip(ткань, 0.75, 1.25)


def kosovorotka(img, verbose=True):
    """Переписать картинку рубахи прямо в Блендере. img — bpy.types.Image."""
    # КАРТИНКУ НАДО СНАЧАЛА ЗАСТАВИТЬ ЗАГРУЗИТЬСЯ. Блендер держит ссылку на
    # файл и подтягивает пиксели лениво; foreach_get на незагруженной картинке
    # молча отдаёт нули. В первый раз это стоило целого прогона: маска вышла
    # «стан 100%, тесьма 0%», рубаха уехала в игру ровно-синей без единой
    # нитки, и по картинке этого было не отличить от «так и задумано».
    if not img.has_data:
        img.reload()
    w, h = img.size
    a = np.empty(w * h * 4, dtype=np.float32)
    img.pixels.foreach_get(a)
    a = a.reshape(h, w, 4)
    if float(a[..., :3].std()) < 1e-4:
        raise RuntimeError("картинка рубахи прочиталась ровной (std %.2e) — "
                           "пиксели не загружены" % a[..., :3].std())
    a[..., :3] = repaint(a[..., :3].astype(np.float64), verbose).astype(np.float32)
    img.pixels.foreach_set(a.reshape(-1))
    img.update()
    _detach(img, "kosovorotka")
    return img


def _detach(img, name):
    """Отвязать картинку от файла ассета и сохранить рядом.

    БЕЗ ЭТОГО ПРАВКА НЕ ДОЕДЕТ В ИГРУ. Картинка в Блендере и файл на диске —
    разные вещи: мы поменяли пиксели в памяти, а вывод в glTF при подходящем
    формате просто КОПИРУЕТ исходный файл, и в игру уезжает нетронутая
    индийская парча. Ровно та же ловушка, что с кэшем импорта Godot: смотришь
    на неизменившийся кадр и ищешь причину где угодно, кроме настоящей.
    Пишем новый файл во временную папку и переводим картинку на него; заодно
    ассет в общей папке MPFB остаётся нетронутым.
    """
    import os
    import bpy
    d = os.path.join(bpy.app.tempdir, "ткань")
    os.makedirs(d, exist_ok=True)
    p = os.path.join(d, name + ".png")
    img.filepath_raw = p
    img.file_format = 'PNG'
    img.save()
    img.filepath = p
    print("[ткань] картинка отвязана от ассета -> %s (%d КБ)"
          % (p, os.path.getsize(p) // 1024))


def repaint(rgb, verbose=True):
    """Вся работа над картинкой, в ЛИНЕЙНОМ цвете. Отдельно от Блендера —
    чтобы то же самое можно было проверить на голом файле и посмотреть глазами
    до того, как собирать всего героя."""
    h, w = rgb.shape[:2]
    фон, лин = _фон(rgb, verbose)
    лён = s2l(ЛЁН) if лин else np.asarray(ЛЁН)
    вышивка = s2l(ВЫШИВКА) if лин else np.asarray(ВЫШИВКА)
    обводка = s2l(ОБВОДКА) if лин else np.asarray(ОБВОДКА)
    стан = np.all(np.abs(rgb - фон) < 0.004, axis=-1)
    тесьма = ~стан
    # НЕ ВСЁ НЕ-СТАН — ТЕСЬМА. В правом нижнем углу развёртки лежит крупный
    # кусок другой ткани (в исходнике — тёмно-красные соты). Если покрасить
    # его как вышивку, на рубахе появится красная панель в ладонь величиной.
    # Отличаем по ширине: вышивка узкая, полоса в несколько миллиметров, и
    # окно 41x41 никогда не заполняется ею целиком; крупный кусок заполняет.
    # Окно берём шире самой широкой полосы вышивки (планка на груди — около
    # 100 пикселей), чтобы планка осталась вышивкой, а кусок ткани — нет.
    крупное = _box_mean(тесьма.astype(np.float64), 56) > 0.97
    крупное = _box_mean(крупное.astype(np.float64), 30) > 0.0   # с каймой
    тесьма &= ~крупное
    стан |= крупное
    if verbose:
        print("[рубаха] стан %.1f%% пикселей, тесьма %.1f%%"
              % (100 * стан.mean(), 100 * тесьма.mean()))
    # САМОПРОВЕРКА. У этой развёртки тесьма — около десятой части холста.
    # Ноль означает, что маска не нашлась (и рубаха выйдет без вышивки),
    # а половина — что фон определён неверно (и вышивкой станет вся рубаха).
    # И то и другое в кадре выглядит «как задумано», поэтому ловим числом.
    if not 0.03 <= тесьма.mean() <= 0.25:
        raise RuntimeError("маска тесьмы неправдоподобна: %.1f%% холста"
                           % (100 * тесьма.mean()))

    ткань = _weave(h, w)
    out = лён[None, None, :] * ткань[..., None]

    # ТЕСЬМА. Внутри маски яркость исходника говорит, где была золотая нить, а
    # где тёмный фон узора: по ней и раскладываем два цвета вышивки, и рисунок
    # ложится по тем же местам, где был, только другими нитками.
    if тесьма.any():
        L = rgb[тесьма].mean(axis=-1)
        p = (L - L.min()) / max(L.max() - L.min(), 1e-6)
        p = np.clip((p - 0.25) / 0.5, 0, 1)[:, None]
        out[тесьма] = вышивка[None, :] * (1 - p) + обводка[None, :] * p
        out[тесьма] *= ткань[тесьма][:, None]

    if verbose:
        print("[рубаха] средний тон стана %s, вышивки %s (линейно)"
              % (np.round(out[стан].mean(0), 4),
                 np.round(out[тесьма].mean(0), 4) if тесьма.any() else "—"))
    return out


def find_image(ob, hint):
    """Картинка цвета материала, включая спрятанную в группе узлов.

    Ловушка, на которой я уже сидел с кожей: у MakeSkin картинка часто лежит
    ВНУТРИ группы узлов, и поиск по верхнему уровню возвращает None молча —
    правка «применяется» в пустоту, а ты смотришь на неизменённый кадр и
    объясняешь его чем угодно, кроме настоящей причины.
    """
    seen = set()

    def walk(nt):
        if nt is None or nt.as_pointer() in seen:
            return None
        seen.add(nt.as_pointer())
        for n in nt.nodes:
            if n.type == 'TEX_IMAGE' and n.image is not None:
                if hint.lower() in n.image.name.lower():
                    return n.image
            if n.type == 'GROUP':
                got = walk(n.node_tree)
                if got is not None:
                    return got
        return None

    for m in ob.data.materials:
        if m is not None and m.use_nodes:
            got = walk(m.node_tree)
            if got is not None:
                return got
    return None


def matte(ob, roughness=0.92, specular=0.18):
    """Снять с ткани блик.

    ИЗМЕРЕНО: ассеты приходят с шероховатостью 0.70 и бликом 0.50 — это
    параметры синтетики. Шерстяное сукно и лён почти не бликуют, и пока блик
    на месте, никакая покраска не сделает ткань тёмной: на белом окружении
    чёрная краска даёт 0.067 вместо нуля — светит отражение, а не основа.
    """
    for m in ob.data.materials:
        if m is None or not m.use_nodes:
            continue
        for n in m.node_tree.nodes:
            if n.type == 'BSDF_PRINCIPLED':
                n.inputs["Roughness"].default_value = roughness
                n.inputs["Specular IOR Level"].default_value = specular


def tuck(inner, outer, gap=0.004, reach=0.022, verbose=True):
    """Заправить нижний слой под верхний: убрать пробой ткани сквозь ткань.

    ПОЧЕМУ НЕ ХВАТИЛО СМЕЩЕНИЯ ПО НОРМАЛИ. Слои разводились тем, что каждому
    следующему задавался отступ от тела: рубахе 0, пальто 18 мм. Это работает
    в среднем и не работает в частности — отступ у каждого слоя СВОЙ разброс.
    ИЗМЕРЕНО по зазору до тела: у рубахи медиана 6 мм, но местами 23; у пальто
    на локте десятая часть вершин ближе 8.5 мм. Там, где худший случай одного
    встречается с худшим другого, ткань выходит наружу.
    В кадре это выглядело рваными пятнами на рукавах и у подола — я сперва
    списал их на тень, потом на облако (облако там тоже было, отдельное), и
    только раскраска каждого материала в свой цвет показала: сквозь пальто
    торчит рубаха.

    ЧТО ДЕЛАЕМ. Для каждой вершины нижнего слоя ищем ближайшую точку верхнего.
    Если вершина оказалась СНАРУЖИ (по нормали верхнего слоя) и верхний слой
    рядом — уводим её внутрь на gap. Дальние вершины не трогаем вовсе: у
    распахнутого пальто перёд открыт, и заправлять там нечего, а обшлаг рубахи
    и должен выглядывать из рукава.
    """
    import bpy
    from mathutils.bvhtree import BVHTree
    dg = bpy.context.evaluated_depsgraph_get()
    bt = BVHTree.FromObject(outer, dg)
    Mi, Mo = inner.matrix_world, outer.matrix_world
    Mi_inv = Mi.inverted()
    n = 0
    worst = 0.0
    for v in inner.data.vertices:
        p = Mi @ v.co
        loc, nrm, idx, dist = bt.find_nearest(p, reach)
        if loc is None:
            continue
        if (p - loc).dot(nrm) <= 0.0:
            continue                      # уже внутри — не трогаем
        v.co = Mi_inv @ (loc - nrm * gap)
        worst = max(worst, dist)
        n += 1
    if verbose:
        print("[слои] %s под %s: заправлено вершин %d из %d, самая наружная "
              "была на %.1f мм" % (inner.name, outer.name, n,
                                   len(inner.data.vertices), worst * 1000))
    return n


def pad(img, tol=0.06, verbose=True):
    """Залить служебный фон развёртки цветом ткани.

    ЧТО ЭТО ЛЕЧИТ. У ассетов одежды пустое место на холсте закрашено ярким
    служебным цветом — у пальто это оранжевый (0.94, 0.40, 0.00) на 37.4%
    холста при цвете сукна (0.54, 0.63, 0.64). Пока текстура читается один к
    одному, он не мешает: острова развёртки его не задевают. Но в игре
    текстура читается С МИП-УРОВНЕЙ, а мип — это усреднение соседей: у самого
    края острова в выборку попадает фон, и оранжевый затекает внутрь. В кадре
    это рваные грязно-зелёные пятна ровно там, где острова узкие — на плечах и
    рукавах, — и выглядят они убедительно похоже на самозатенение.

    Я на это и попался: сперва списал на акне тени (пятна ходили за солнцем —
    ещё бы, это же затенение поверхности), потом на объёмное облако (при
    ясном небе их стало меньше). Обе догадки были правдоподобны и обе неверны.
    Показала правду раскраска: убрал текстуры, раскрасил каждый материал в
    свой ровный цвет — пятна исчезли, хотя и свет, и облака, и слои остались.

    Лечится заливкой: фон красится в средний цвет ткани, и затекать становится
    нечему. Это стандартная «прокладка» (padding) развёртки; обычно её делают
    растеканием цвета от краёв островов, но у ровной вязки хватает и среднего.
    """
    if not img.has_data:
        img.reload()
    w, h = img.size
    a = np.empty(w * h * 4, dtype=np.float32)
    img.pixels.foreach_get(a)
    a = a.reshape(h, w, 4)
    рамка = np.concatenate([a[:4].reshape(-1, 4), a[-4:].reshape(-1, 4),
                            a[:, :4].reshape(-1, 4), a[:, -4:].reshape(-1, 4)])
    фон = рамка[:, :3].mean(0)
    # Маска считается поканально и на месте: холст 4096x4096 — это 268 МБ на
    # сам массив, и одно неосторожное np.abs(a[..., :3] - фон) добавляет ещё
    # три таких же временных.
    m = np.ones(a.shape[:2], dtype=bool)
    for c in range(3):
        m &= np.abs(a[..., c] - фон[c]) < tol
    # ЕСЛИ ФОН И ЕСТЬ ЦВЕТ ТКАНИ — заливать нечего и незачем: так у рубахи,
    # где ровный тон стана занимает 87% холста и служит самой одеждой.
    if m.mean() > 0.80 or m.mean() < 0.02:
        if verbose:
            print("[прокладка] %s: фон %s занимает %.1f%% — не трогаю"
                  % (img.name, np.round(фон, 3), 100 * m.mean()))
        return False
    inv = ~m
    ткань = np.array([a[..., c][inv].mean() for c in range(3)])
    for c in range(3):
        a[..., c][m] = ткань[c]
    a[..., 3] = 1.0
    img.pixels.foreach_set(a.reshape(-1))
    img.update()
    if verbose:
        print("[прокладка] %s: фон %s (%.1f%% холста) залит цветом ткани %s"
              % (img.name, np.round(фон, 3), 100 * m.mean(), np.round(ткань, 3)))
    _detach(img, "прокладка_" + img.name.rsplit(".", 1)[0])
    return True


def images(ob):
    """Все картинки ЦВЕТА у объекта, включая спрятанные в группах узлов."""
    out, seen = [], set()

    def walk(nt):
        if nt is None or nt.as_pointer() in seen:
            return
        seen.add(nt.as_pointer())
        for n in nt.nodes:
            if n.type == 'TEX_IMAGE' and n.image is not None:
                # карты нормалей и блика заливать средним нельзя: у них
                # значение пикселя — не цвет, а направление и шероховатость.
                # Проверяем и по связям, и по имени: у одного и того же ассета
                # карта может идти и через NORMAL_MAP, и через BUMP, и напрямую.
                nm = n.image.name.lower()
                if any(k in nm for k in ("nrm", "normal", "bump", "spec",
                                         "rough", "_disp")):
                    continue
                if any(l.to_node.type in ('NORMAL_MAP', 'BUMP')
                       for l in nt.links if l.from_node is n):
                    continue
                if n.image not in out:
                    out.append(n.image)
            if n.type == 'GROUP':
                walk(n.node_tree)
    for m in ob.data.materials:
        if m is not None and m.use_nodes:
            walk(m.node_tree)
    return out


def flat(ob, verbose=True):
    """Отключить карту нормалей у одежды.

    ИЗМЕРЕНО В САМОЙ ИГРЕ: на плече и рукаве пальто держалось рваное
    грязно-зелёное пятно. Я объяснял его по очереди акне тени (пятно ходило за
    солнцем), объёмным облаком (при ясном небе его меньше) и затеканием
    служебного фона развёртки на мип-уровнях (фон у пальто ярко-оранжевый на
    37.4% холста). Первые две догадки были неверны, третья верна сама по себе,
    но пятна не убрала. Снял карту нормалей — пятно исчезло начисто.

    Это согласуется с самим ассетом: в его .mhmat стоит `shaderConfig normal
    False` и `bump False` — АВТОР ЕЁ НЕ ПРЕДПОЛАГАЛ. Карта 4096x4096 с вязкой
    в натуральную величину на мип-уровнях усредняется в бессмыслицу, и шейдер
    честно светит по бессмысленным нормалям.
    """
    n = 0
    for m in ob.data.materials:
        if m is None or not m.use_nodes:
            continue
        nt = m.node_tree
        for b in [x for x in nt.nodes if x.type == 'BSDF_PRINCIPLED']:
            for l in list(nt.links):
                if l.to_socket == b.inputs["Normal"]:
                    nt.links.remove(l)
                    n += 1
    if verbose and n:
        print("[ткань] %s: снята карта нормалей (%d связей)" % (ob.name, n))
    return n


def _axis_table(body, step=0.02):
    """Таблица оси тела по высоте: центр и радиус поперечного сечения.

    Считается ОДИН раз. Первый заход искал сечение заново для каждой вершины
    пальто — 19158 вершин тела на 5036 вершин одежды, это девяносто шесть
    миллионов сравнений на питоне, то есть минуты вместо долей секунды.
    """
    import numpy as np
    co = np.array([[v.co.x, v.co.y, v.co.z] for v in body.data.vertices])
    z0, z1 = co[:, 2].min(), co[:, 2].max()
    zs = np.arange(z0, z1 + step, step)
    out = []
    for z in zs:
        m = np.abs(co[:, 2] - z) < step
        if m.sum() < 8:
            out.append((z, 0.0, 0.0, 0.0))
            continue
        a = co[m][:, :2]
        c = a.mean(0)
        r = np.linalg.norm(a - c, axis=1)
        out.append((z, c[0], c[1], float(np.percentile(r, 92))))
    return np.array(out)


def _axis_at(tab, z):
    import numpy as np
    i = int(np.clip(np.searchsorted(tab[:, 0], z) - 1, 0, len(tab) - 1))
    return tab[i, 1], tab[i, 2], tab[i, 3]


def taper(coat, body, hem_ratio=1.28, verbose=True):
    """Убрать А-силуэт: пальто расширяется книзу по-женски.

    ЧТО ВИДНО СЗАДИ, ЧЕГО НЕ ВИДНО СПЕРЕДИ. Спереди пальто распахнуто, и его
    очертание задают полы; сзади оно цельное, и там читается крой. У нас там
    читался женский: подол расходится от груди трапецией, талии нет, зад шире
    плеч. Это не «пышные плечи» — плечи как раз в норме (медиана зазора до
    тела 10.4 мм при портновских 10-15), — но заказчик назвал ровно то место,
    где костюм выдаёт себя.

    ЧИСЛО, К КОТОРОМУ ВЕДЁМ. У женского пальто-трапеции подол по обхвату
    выходит в 1.6-1.9 раза шире бёдер, у мужского сюртука или поддёвки — в
    1.15-1.3: он либо прямой, либо чуть расклешён от талии, чтобы не мешал
    шагу. Берём 1.28 — расклешение остаётся, женская трапеция уходит.

    КАК. Ниже талии каждая вершина подтягивается К ОСИ ТЕЛА: её вынос сверх
    оси умножается на множитель, равный 1 на талии и падающий к подолу.
    Складки сохраняются — они живут в разбросе выноса, а множитель общий.
    """
    import numpy as np
    tab = _axis_table(body)
    z0, z1 = tab[0, 0], tab[-1, 0]
    H = z1 - z0
    z_waist = z0 + 0.60 * H
    z_hip = z0 + 0.53 * H
    cx_h, cy_h, r_hip = _axis_at(tab, z_hip)
    if r_hip <= 0:
        print("[пальто] ось тела не снялась — расклешение не трогаю")
        return 0

    низ = [v for v in coat.data.vertices if v.co.z < z_waist]
    if not низ:
        return 0
    z_hem = min(v.co.z for v in низ)
    подол = [v for v in низ if v.co.z < z_hem + 0.05]

    def girth():
        return float(np.percentile(
            [np.hypot(v.co.x - cx_h, v.co.y - cy_h) for v in подол], 92))

    было = girth() / r_hip
    if было <= hem_ratio:
        if verbose:
            print("[пальто] подол/бедро %.2f — уже не трапеция, не трогаю" % было)
        return 0
    n = 0
    for v in низ:
        t = (z_waist - v.co.z) / max(z_waist - z_hem, 1e-6)   # 0 талия, 1 подол
        k = 1.0 + t * (hem_ratio / было - 1.0)
        cx, cy, _ = _axis_at(tab, v.co.z)
        v.co.x = cx + (v.co.x - cx) * k
        v.co.y = cy + (v.co.y - cy) * k
        n += 1
    if verbose:
        print("[пальто] подол/бедро было %.2f, стало %.2f (цель %.2f), "
              "двинуто вершин %d" % (было, girth() / r_hip, hem_ratio, n))
    return n


def unbind(ob, кости, verbose=True):
    """Снять с одежды привязку к костям, которых она не должна касаться.

    ИЗМЕРЕНО В ВЫВЕДЕННОМ ФАЙЛЕ: у косоворотки левое бедро держало 13.5% всего
    веса, а правое 3.5% — вчетверо меньше. У пальто, штанов и сапог стороны
    сходятся в пределах 0.5%, то есть это не общее свойство переноса весов, а
    беда именно этой сетки: подол рубахи висит на уровне паха, туда достают
    обе ноги, и перенос по близости раздал вес как попало. На шаге подол
    дёргало в одну сторону.

    ЗЕРКАЛО ЗДЕСЬ НЕ ПОМОГАЕТ, И ЭТО ПРОВЕРЕНО. Первым заходом я усреднял вес
    вершины с её отражением по x — расхождение сторон осталось прежним, 4.8%,
    потому что зеркало у этой сетки находится с точностью лишь 23 мм:
    топология несимметрична, пары попросту нет.

    ПРАВИЛЬНО ИНАЧЕ: рубахе нечего висеть на бёдрах вовсе. Рубаха держится на
    плечах и на тазе, и при взмахе ноги её подол остаётся на месте — это видно
    на любом живом человеке. Убираем бедренные группы и раздаём их вес
    остальным пропорционально.
    """
    группы = [g for g in ob.vertex_groups if g.name in кости]
    if not группы:
        if verbose:
            print("[привязка] %s: снимать нечего" % ob.name)
        return 0
    def доля():
        # СПИСОК ИМЁН ЧИТАЕТСЯ ЗАНОВО КАЖДЫЙ РАЗ. Снятый список после удаления
        # групп врёт: индексы сдвигаются, и отчёт показывал снятую кость среди
        # оставшихся — «снято LeftUpLeg, теперь держат ... LeftUpLeg 13.4%».
        имена = [g.name for g in ob.vertex_groups]
        s, t = {}, 0.0
        for v in ob.data.vertices:
            ws = {имена[g.group]: g.weight for g in v.groups}
            n = sum(ws.values()) or 1.0
            for k, x in ws.items():
                s[k] = s.get(k, 0.0) + x / n
                t += x / n
        return {k: 100 * x / (t or 1.0) for k, x in s.items()}

    до = доля()
    idx = {g.index for g in группы}
    n = 0
    for v in ob.data.vertices:
        if any(g.group in idx for g in v.groups):
            n += 1
    for g in группы:
        ob.vertex_groups.remove(g)
    после = доля()
    if verbose:
        было = ", ".join("%s %.1f%%" % (k, до.get(k, 0.0)) for k in кости)
        print("[привязка] %s: снято %s — задето вершин %d из %d; "
              "теперь держат %s" % (ob.name, было, n, len(ob.data.vertices),
                                    ", ".join("%s %.1f%%" % (k, v) for k, v in
                                              sorted(после.items(),
                                                     key=lambda kv: -kv[1])[:3])))
    return n
