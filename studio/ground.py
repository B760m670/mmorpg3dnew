#!/usr/bin/env python3
"""СТОПЫ НА ЗЕМЛЮ. Вторая половина работы с записью движения.

ЧТО ЗАПИСЬ ДАЁТ И ЧЕГО НЕ ДАЁТ. Захват CMU переносит ПОВОРОТЫ суставов — это
настоящее человеческое движение, и его не сочинить. Но сдвиг таза в записи —
это высота таза ТОГО человека. У него своя длина ног, у нашего своя. Разница
в пару сантиметров даёт ровно те два порока, по которым игрока не обмануть:

  ПАРЕНИЕ — тело идёт на пару сантиметров выше пола, тени под подошвой нет,
    человек висит. Замер: кость LeftFoot не опускалась ниже 0.102 м, а
    лодыжка стоящего человека — это 0.07–0.08 м. Значит висим.
  КОНЬКОБЕЖЕЦ — опорная стопа стоит на земле, а тело едет мимо неё. Самый
    заметный порок игровой ходьбы; глаз ловит его мгновенно.

ПОЧЕМУ ЭТО ЧИСТАЯ АРИФМЕТИКА, А НЕ ПЕРЕБОР. Сдвиг корня переносит ВСЁ тело
жёстко: сдвинул таз на вектор — вся сетка, включая подошву, сдвинулась на тот
же вектор. Значит поправку можно вычислить один раз по замеру и применить, не
пересчитывая позу заново. Это не приближение, это свойство жёсткого сдвига.

ЧТО ЗДЕСЬ ДЕЛАЕТСЯ, по шагам:

  1. ПОДОШВА ПО СЕТКЕ, а не по кости. Кость лодыжки — не низ ноги; между ней
     и полом ещё вся стопа. Меряем самые нижние вершины, у которых вес в
     группах LeftFoot/LeftToeBase больше половины. Это то, что касается
     земли на самом деле.
  2. КАСАНИЕ. Земля — самая низкая точка подошвы за весь цикл. Стопа в
     касании, если её подошва в пределах 2 см от этой земли.
  3. ВЫСОТА ТАЗА ПОДГОНЯЕТСЯ ЛИНЕЙНО: z_нов = a·z_зап + b. Не одним сдвигом,
     потому что одного сдвига мало: если у нас ноги короче, то в момент
     полного шага подошва не достаёт до пола, а в середине опоры уже
     проваливается. Постоянная поправка может исправить только одно из двух.
     Коэффициенты a и b находятся наименьшими квадратами по кадрам касания —
     то есть буквально «подобрать качку таза так, чтобы опорная подошва
     лежала на нуле».
  4. ГОРИЗОНТАЛЬ ОТ СТОП, а не от записи. Пока опорная стопа одна и та же и
     стоит на земле, она обязана оставаться на месте. Сколько она уехала —
     на столько же назад двигаем корень. Накопленная поправка складывается;
     при смене опорной ноги ничего не корректируем, просто держим
     накопленное. Получается ровно то, что в играх называют root motion:
     скорость персонажа задаётся его стопами, а не записанной кривой.

ЧЕГО ЭТА ПРАВКА НЕ УМЕЕТ, и это важно сказать честно: корень один, а ног две.
В двойной опоре (обе стопы на земле) закрепить можно только одну; вторая
доедет. Убрать остаток может лишь ОБРАТНАЯ КИНЕМАТИКА ног — она гнёт колено,
а не двигает всё тело. Здесь её нет; остаток измеряется и печатается числом.

Запуск (внутри Блендера, после mocap.load_cmu):
  import ground
  ground.report(body, arm, n)      # как есть
  ground.lock(body, arm, n)        # поставить на землю
  ground.report(body, arm, n)      # что изменилось
"""
import bpy
from mathutils import Vector

FOOT = {"L": ("LeftFoot", "LeftToeBase"), "R": ("RightFoot", "RightToeBase")}
CONTACT = 0.020   # 20 мм от земли — ещё касание
NLOW = 24         # по скольким нижним вершинам считаем точку опоры


def _sole_groups(body):
    """Индексы весовых групп стопы. Ошибиться тут — мерить не то."""
    out = {}
    for s, names in FOOT.items():
        idx = [body.vertex_groups[n].index for n in names
               if n in body.vertex_groups]
        out[s] = set(idx)
        if not idx:
            print("[земля] НЕТ групп стопы %s: %s" % (s, names))
    return out


def measure(body, frames):
    """Для каждого кадра: высота подошвы и точка опоры каждой стопы.

    Читаем ВЫЧИСЛЕННУЮ сетку: после арматуры, разглаживания и маски. Маска
    выбрасывает вершины, поэтому по номерам вершин сопоставлять нельзя —
    веса берём прямо с вычисленной сетки, они там сохраняются.
    """
    gi = _sole_groups(body)
    M = body.matrix_world
    res = {"L": [], "R": []}
    for f in frames:
        bpy.context.scene.frame_set(f)
        dg = bpy.context.evaluated_depsgraph_get()
        ev = body.evaluated_get(dg)
        me = ev.to_mesh()
        pts = {"L": [], "R": []}
        for v in me.vertices:
            w = {}
            for g in v.groups:
                for s, idx in gi.items():
                    if g.group in idx:
                        w[s] = w.get(s, 0.0) + g.weight
            for s, ww in w.items():
                if ww > 0.5:
                    pts[s].append(M @ v.co)
        ev.to_mesh_clear()
        for s in ("L", "R"):
            p = sorted(pts[s], key=lambda q: q.z)[:NLOW]
            if not p:
                res[s].append((None, None))
                continue
            z = p[0].z
            c = sum(p, Vector()) / len(p)
            res[s].append((z, Vector((c.x, c.y, 0.0))))
    return res


def _contacts(res, n):
    """Где стопа стоит на земле.

    ПЕРВЫЙ ВАРИАНТ ЭТОЙ ФУНКЦИИ БЫЛ НЕВЕРЕН, и ошибка поучительная. Я считал
    землёй самую низкую точку за весь цикл и называл опорой всё, что в двух
    сантиметрах от неё. Опорных кадров нашлось 2 из 40 — потому что тело
    ПАРИТ: записанный человек ростом около 1.81 м (таз 0.96 м), наш герой
    1.727 м, ноги короче, и до пола подошва просто не доходит. Определять
    опору по расстоянию до пола, когда пола никто не касается, — замкнутый
    круг: пока не поставишь на землю, не узнаешь, где земля.

    ОПОРА УЗНАЁТСЯ ПО ДВИЖЕНИЮ, а не по высоте. Стоящая стопа НЕ ЕДЕТ
    горизонтально — вот признак, которому высота не нужна. Высота остаётся
    вторым условием, но своя для каждой ноги и с широким допуском.
    """
    con = {}
    for s in ("L", "R"):
        z = [q for q, _ in res[s]]
        c = [p for _, p in res[s]]
        zmin = min(q for q in z if q is not None)
        v = []
        for i in range(n):
            if i == 0 or c[i] is None or c[i - 1] is None:
                v.append(0.0)
            else:
                v.append((c[i] - c[i - 1]).length)
        # скорость: медиана по всему циклу — половина кадров это мах ногой,
        # так что порог в треть медианы отделяет стояние от переноса
        med = sorted(v)[n // 2] if n else 0.0
        lim = max(0.010, 0.45 * med)
        c = [z[i] is not None and z[i] < zmin + 0.045 and v[i] < lim
             for i in range(n)]
        # ОПОРА — ЭТО ОТРЕЗОК, А НЕ РОССЫПЬ КАДРОВ. Скорость стопы в стоянии
        # не идеально нулевая: она дрожит и на один-два кадра выскакивает за
        # порог, разрывая опору на куски. Сырой признак дал 24 «постановки
        # стопы» на 2.6 секунды ходьбы, где их пять. Поэтому дырки в один-два
        # кадра заклеиваем, а огрызки короче трёх кадров выбрасываем — это
        # обычная чистка признака, «замыкание и размыкание».
        for i in range(1, n - 2):
            if c[i - 1] and not c[i] and (c[i + 1] or c[i + 2]):
                c[i] = True
        i = 0
        while i < n:
            if c[i]:
                j = i
                while j < n and c[j]:
                    j += 1
                if j - i < 3:
                    for k in range(i, j):
                        c[k] = False
                i = j
            else:
                i += 1
        con[s] = c
    zs = [z for s in ("L", "R") for z, _ in res[s] if z is not None]
    ground = min(zs) if zs else 0.0
    return ground, con


def report(body, arm, frames, title=""):
    """Числа про стопы. Печатает и возвращает их же."""
    res = measure(body, frames)
    ground, con = _contacts(res, len(frames))
    print("-" * 66)
    print("СТОПЫ %s" % title)
    print("  земля (низшая точка подошвы за цикл): %+.3f м" % ground)
    for s in ("L", "R"):
        z = [q for q, _ in res[s] if q is not None]
        c = sum(con[s])
        print("  подошва %s: %+.3f..%+.3f м, кадров касания %d из %d"
              % (s, min(z), max(z), c, len(frames)))
    # УРОВЕНЬ ПОЛА ПО ШАГАМ. Раньше здесь считался разброс высоты по всем
    # опорным кадрам разом — и это мерило не походку, а ширину моей же
    # полосы допуска в поиске опоры: чем ближе стопы к полу, тем больше
    # кадров в неё попадает и тем «хуже» выходило число. Правильный вопрос
    # другой: КАЖДЫЙ ЛИ ШАГ ВСТАЁТ НА ОДИН И ТОТ ЖЕ ПОЛ. Поэтому опорные
    # кадры собираются в отрезки — по одному на каждую постановку стопы, —
    # и у каждого берётся своя высота. Разброс между шагами и есть ответ.
    steps = []
    for s in ("L", "R"):
        run = []
        for i in range(len(frames)):
            if con[s][i] and res[s][i][0] is not None:
                run.append(res[s][i][0])
            elif run:
                steps.append((s, sorted(run)[len(run) // 2], len(run)))
                run = []
        if run:
            steps.append((s, sorted(run)[len(run) // 2], len(run)))
    if steps:
        lv = [z for _, z, _ in steps]
        spread = max(lv) - min(lv)
        print("  постановок стопы: %d, уровень пола %+.1f..%+.1f мм"
              % (len(steps), min(lv) * 1000, max(lv) * 1000))
        print("     " + "  ".join("%s%+.0f" % (s, z * 1000) for s, z, _ in steps))
        print("  разброс уровня между шагами: %.1f мм%s"
              % (spread * 1000, "" if spread < 0.015 else "  — ПОЛ ГУЛЯЕТ"))
    else:
        spread = 0.0
        print("  постановок стопы не найдено")
    cz = [z for s in ("L", "R")
          for (z, _), k in zip(res[s], con[s]) if k and z is not None]
    if cz:
        m = sum(cz) / len(cz)
        print("  опорная подошва в среднем: %+.1f мм от пола%s"
              % (m * 1000, "" if abs(m) < 0.005 else
                 ("  — ПАРИТ" if m > 0 else "  — ТОНЕТ")))
    # проскальзывание: сумма сдвигов опорной точки, пока опорная нога та же
    slip = 0.0
    prev = None
    for i in range(len(frames)):
        st = None
        for s in ("L", "R"):
            if con[s][i] and res[s][i][1] is not None:
                if st is None or res[s][i][0] < res[st][i][0]:
                    st = s
        if st and prev and prev[0] == st:
            slip += (res[st][i][1] - prev[1]).length
        prev = (st, res[st][i][1]) if st else None
    print("  проскальзывание опорной подошвы: %.1f мм за цикл%s"
          % (slip * 1000, "" if slip < 0.05 else "  — КОНЬКОБЕЖЕЦ"))
    fly = min(z for s in ("L", "R") for z, _ in res[s] if z is not None)
    print("  зазор под самой низкой подошвой: %+.1f мм%s"
          % (fly * 1000, "" if abs(fly) < 0.005 else
             ("  — ПАРИТ" if fly > 0 else "  — ТОНЕТ")))
    # ПРОВАЛ ПОД ПОЛ отдельно от всего: поправка таза одна на две ноги, и в
    # двойной опоре она может держать только одну. Сколько кадров и насколько
    # глубоко вторая уходит под пол — это и есть остаток, который снимает
    # только обратная кинематика ног.
    deep = [(f, s, z) for i, f in enumerate(frames) for s in ("L", "R")
            for z in [res[s][i][0]] if z is not None and z < -0.005]
    if deep:
        w = min(deep, key=lambda t: t[2])
        print("  под полом: %d раз из %d, глубже всего %s на %.1f мм (кадр %d)"
              % (len(deep), 2 * len(frames), w[1], -w[2] * 1000, w[0]))
    print("-" * 66)
    return res, ground, con, slip, spread


def lock(body, arm, frames, root="Hips"):
    """Поставить на землю: подогнать высоту таза и снять проскальзывание.

    Возвращает (нижняя и верхняя поправка таза, горизонтальная поправка).
    """
    res = measure(body, frames)
    ground, con = _contacts(res, len(frames))
    pb = arm.pose.bones[root]
    rest = arm.data.bones[root].matrix_local.to_3x3()

    # 1. ВЫСОТА ТАЗА ПО КАДРАМ, а не одним числом.
    #
    #    ТРЕТИЙ ПОДХОД, И ПРИЧИНА ЕГО ТАКАЯ. Сама запись CMU не стоит на
    #    месте по высоте: за 2.6 секунды таз в ней поднимается с 0.889 до
    #    0.98 м, и опорная стопа вместе с ним — с нуля до 10 см. Это видно
    #    прямо в сыром ASF, без нашего рига (посчитано прямой кинематикой),
    #    значит это свойство записи, а не нашей ошибки. Постоянный сдвиг
    #    такое не лечит: подберёшь по началу — к концу человек висит на
    #    десять сантиметров.
    #
    #    Поэтому таз правится КРИВОЙ: в каждом кадре опоры цель — опустить
    #    самую низкую из стоящих подошв ровно на пол; между опорами кривая
    #    протягивается линейно; потом сглаживается скользящим средним, чтобы
    #    поправка не дёргалась покадрово. Это ровно то, что в играх зовут
    #    подстройкой таза при постановке стоп.
    #
    #    Берётся МИНИМУМ из двух подошв, а не средняя: в двойной опоре обе
    #    стопы на земле, и если целиться в верхнюю, нижняя уйдёт под пол.
    #    Провал заметнее парения.
    tgt = [None] * len(frames)
    for i in range(len(frames)):
        zz = [res[s][i][0] for s in ("L", "R")
              if con[s][i] and res[s][i][0] is not None]
        if zz:
            tgt[i] = -min(zz)
    known = [i for i, v in enumerate(tgt) if v is not None]
    if not known:
        raise RuntimeError("опорных кадров не нашлось — нечем ставить на землю")
    for i in range(len(frames)):          # протянуть между опорами
        if tgt[i] is not None:
            continue
        lo_i = max([k for k in known if k < i], default=None)
        hi_i = min([k for k in known if k > i], default=None)
        if lo_i is None:
            tgt[i] = tgt[hi_i]
        elif hi_i is None:
            tgt[i] = tgt[lo_i]
        else:
            w = (i - lo_i) / (hi_i - lo_i)
            tgt[i] = tgt[lo_i] * (1 - w) + tgt[hi_i] * w
    W = max(1, len(frames) // 24)         # окно сглаживания ≈ треть шага
    sm = []
    for i in range(len(frames)):
        a0, b0 = max(0, i - W), min(len(frames), i + W + 1)
        sm.append(sum(tgt[a0:b0]) / (b0 - a0))
    print("[земля] таз по кадрам: поправка %+.1f..%+.1f мм, опорных кадров %d"
          % (min(sm) * 1000, max(sm) * 1000, len(known)))

    # 1б. ПРЕЖНИЙ ВАРИАНТ — ПОСТОЯННЫЙ СДВИГ ПО МЕДИАНЕ.
    #
    #    ЗДЕСЬ БЫЛА ВТОРАЯ МОЯ ОШИБКА В ЭТОМ ФАЙЛЕ. Я подгонял высоту таза
    #    прямой z' = a·z + b наименьшими квадратами — и коэффициент a упёрся
    #    в ограничитель 0.70, то есть подгонка сплющила качку таза на треть,
    #    не исправив высоту. Причина простая: разница в длине ног у нас с
    #    записанным человеком около 4%, значит и амплитуда качки отличается
    #    на четыре процента от двух сантиметров — меньше миллиметра. Такой
    #    величины в данных нет, есть только шум, и прямая подгонялась к шуму.
    #    Наклон, которого нет, находить нельзя. Остаётся сдвиг.
    #
    #    Постоянный сдвиг по медиане опорных подошв (median, а не среднее:
    #    в начале записи человек стоит, и его подошва ниже) снял парение в
    #    среднем — с +28 до −0.9 мм, — но оставил разброс 45 мм. Разброс и
    #    есть тот самый уход записи; его лечит только кривая выше.

    # 2. ГОРИЗОНТАЛЬ: пока опорная нога та же — держим точку опоры на месте
    off = [Vector((0, 0, 0)) for _ in frames]
    acc = Vector((0, 0, 0))
    prev = None
    for i in range(len(frames)):
        st = None
        for s in ("L", "R"):
            if con[s][i] and res[s][i][1] is not None:
                if st is None or res[s][i][0] < res[st][i][0]:
                    st = s
        if st and prev and prev[0] == st:
            acc = acc - (res[st][i][1] - prev[1])
        off[i] = acc.copy()
        prev = (st, res[st][i][1]) if st else None
    print("[земля] горизонталь: накоплено %.3f м поправки на %d кадрах"
          % (off[-1].length, len(frames)))

    # 3. ПРИМЕНИТЬ. Ключи корня переписываются в костной системе координат —
    #    в той же, в какой их поставил разбор захвата.
    Wi = arm.matrix_world.to_3x3().inverted()
    for i, f in enumerate(frames):
        bpy.context.scene.frame_set(f)
        # поправка задана в мире; в кость она переводится теми же двумя
        # матрицами, какими разбор захвата ставил исходный ключ
        d = Vector((off[i].x, off[i].y, sm[i]))
        pb.location = pb.location + rest.transposed() @ (Wi @ d)
        pb.keyframe_insert("location", frame=f)
    bpy.context.view_layer.update()
    return min(sm), max(sm), off[-1].length
