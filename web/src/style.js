// СТИЛЬ: ОБЩИЙ КУСОК ШЕЙДЕРА ДЛЯ ВСЕГО, ЧТО ОСВЕЩЕНО.
//
// Здесь решается, как физический свет превращается в рисованный. Одно место на
// всю сцену — иначе земля и вода поедут в разные стороны, и кадр развалится на
// «нарисованный берег и фотографическую воду».
//
// ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО: постеризации готового кадра. Уменьшить число
// цветов в фотографии — это фотография с уменьшенным числом цветов, ни на шаг
// не ближе к рисунку. Ступенями режется ОСВЕЩЁННОСТЬ (n·l) ДО умножения на цвет
// поверхности: тогда граница света и тени становится ЛИНИЕЙ, идущей по форме
// предмета, а это и есть то, что рисует художник.
//
// ТРИ ВЕЩИ, КОТОРЫЕ ДЕЛАЮТ КАДР АНИМЕ, А НЕ «ИГРОЙ С ЦЕЛЛ-ШЕЙДИНГОМ»:
//
// 1. ТЕНЬ — ДРУГОГО ЦВЕТА, А НЕ ПРОСТО ТЕМНЕЕ. В природе тень освещена небом, и
//    она действительно синее света Солнца; в аниме этот сдвиг ПРЕУВЕЛИЧЕН, и
//    именно он читается как «нарисовано». Тень зелёной травы — сине-зелёная,
//    почти бирюзовая, а не тёмно-зелёная.
//
// 2. СТУПЕНЬКА ИДЁТ ПО КРУПНОЙ ФОРМЕ. Если резать по геометрической нормали, на
//    рельефе с шагом 1 м выйдет крошево из пятен. Художник рисует тень холма
//    ОДНИМ пятном. Поэтому n·l берётся от СГЛАЖЕННОЙ нормали (радиус 8 м), а
//    мелкая форма остаётся только в цвете.
//
// 3. КРАЙ СТУПЕНЬКИ ПОЧТИ РЕЗКИЙ, НО НЕ РЕЗКИЙ. Полностью жёсткая граница
//    ступенчатится на склоне; ширина перехода берётся такой, чтобы она была
//    порядка пикселя, — тогда линия чистая на любом расстоянии.
export const STYLE_GLSL = /* glsl */`
// anime: 0 — физический кадр, 1 — рисованный. Оставлено переключателем, потому
// что физический слой остаётся источником правды и по нему сверяется свет.
uniform float anime;
uniform vec3 shadowTint;     // во что уходит тень (умножается на свет неба)

// Ступени освещённости. Две границы: полутень и свет. Третья ступень (глубокая
// тень) появляется сама там, куда не достаёт и небо.
float toonBands(float ndl, float w) {
	float a = smoothstep(0.24 - w, 0.24 + w, ndl);
	float b = smoothstep(0.58 - w, 0.58 + w, ndl);
	return 0.42 * a + 0.58 * b;
}

// Ширина перехода в единицах n·l, соответствующая примерно одному пикселю.
// Берётся из того, как быстро меняется освещённость по экрану: там, где форма
// уходит от света полого, линия обязана быть шире, иначе она рассыплется.
float bandWidth(float ndl) {
	return clamp(fwidth(ndl) * 0.9, 0.004, 0.13);
}

// СВЕТ, КОТОРЫМ КРАСЯТ ПОВЕРХНОСТЬ. Возвращает не яркость, а ЦВЕТ освещения:
// на свету — солнечный, в тени — небесный со сдвигом в холод.
vec3 toonLight(float ndl, vec3 sunColor, vec3 skyColor) {
	float b = toonBands(ndl, bandWidth(ndl));
	vec3 shade = skyColor * shadowTint;
	return mix(shade, sunColor + skyColor * 0.35, b);
}
`;

// Палитра стиля. Держится в одном месте и на JS-стороне тоже — по ней потом
// собираются настоящие цветовые скрипты сцен (色彩設計), где у каждой сцены свой
// набор «свет / тень / дальний план».
export const PALETTE = {
	// Тень уходит в холодную бирюзу — так её кладут в дневных сценах. Число
	// подобрано по кадру, а не взято из головы: при 0.62/0.86/1.15 тень травы
	// перестаёт читаться грязью и становится цветом.
	shadowTint: [0.62, 0.86, 1.15],
};
